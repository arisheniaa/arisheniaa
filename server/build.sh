#!/usr/bin/env bash
# Пересборка сайта arisheniaa из исходников.
#
# На хосте НЕТ и не должно появиться node/npm: сборка целиком идёт внутри
# одноразового контейнера node:22-bookworm-slim, который после себя ничего
# не оставляет. Хост остаётся чистым, а версия node зафиксирована образом,
# а не тем, что случайно установлено на машине.
#
# Память контейнера ограничена жёстко. На хосте 3.8 ГБ, из них уже заняты
# личным сайтом и стеком ORIION; без лимита OOM-killer при тяжёлой сборке
# выбирал бы жертву по своему усмотрению и мог убить чужой сервис. Лимит
# делает так, что при нехватке памяти умирает именно сборка.
#
# Сборка идёт в repo/.design/hybrid/dist, и только после её УСПЕХА результат
# переезжает в site/. Пока сборка не прошла, посетители продолжают видеть
# предыдущую рабочую версию — полусобранный сайт наружу не попадает.
set -euo pipefail

ROOT=/opt/arisheniaa-site
REPO=$ROOT/repo
APP=$REPO/.design/hybrid
NODE_IMAGE=node:22-bookworm-slim

# Ветку берём из самого клона, а не зашиваем константой: у этого репозитория
# она `master`, и зашитый `main` сломал бы пересборку молча — fetch упал бы,
# а set -e остановил бы скрипт на ровном месте через полгода.
BRANCH=$(git -C "$REPO" rev-parse --abbrev-ref HEAD)

# Подтягиваем чужие правки ТОЛЬКО если своих здесь нет. `reset --hard` стирает
# и незакоммиченные правки, и локальные коммиты, которых нет на origin, — а в
# этом клоне такие коммиты есть (правки видимости, пока не принятые в
# репозиторий). Молча снести их означало бы откатить сайт к прошлой версии,
# причём сборка при этом отработала бы «успешно» и ничего не сообщила.
DIRTY=$(git -C "$REPO" status --porcelain)
AHEAD=$(git -C "$REPO" log --oneline "origin/$BRANCH..HEAD" 2>/dev/null | wc -l)

if [ -n "$DIRTY" ] || [ "$AHEAD" -gt 0 ]; then
  echo "==> в клоне есть свои изменения — origin НЕ подтягиваю"
  [ -n "$DIRTY" ] && echo "    незакоммиченных файлов: $(echo "$DIRTY" | wc -l)"
  [ "$AHEAD" -gt 0 ] && echo "    локальных коммитов вне origin: $AHEAD"
  echo "    собираю то, что лежит в клоне сейчас"
else
  echo "==> git pull ($BRANCH)"
  git -C "$REPO" fetch --depth 1 origin "$BRANCH"
  git -C "$REPO" reset --hard FETCH_HEAD
fi
git -C "$REPO" rev-parse --short HEAD

echo "==> npm ci + vite build (в контейнере $NODE_IMAGE)"
docker run --rm \
  -v "$REPO":/app \
  -w /app/.design/hybrid \
  -m 2g --memory-swap 2g \
  -e npm_config_update_notifier=false \
  -e CI=true \
  "$NODE_IMAGE" \
  sh -eu -c 'npm ci --no-audit --no-fund && npm run build'

# Самопроверка из README проекта: «сборка прошла» ничего не значит, потому
# что без обработки tailwind vite всё равно завершается кодом 0 и печатает
# зелёный отчёт, а страница при этом разваливается в одну колонку. Значимый
# признак — что в собранном CSS реально есть утилиты.
echo "==> самопроверка сборки"
test -f "$APP/dist/index.html"       || { echo "ОШИБКА: нет dist/index.html"; exit 1; }
test -f "$APP/dist/storyboard.html"  || { echo "ОШИБКА: нет dist/storyboard.html — потеряна вторая точка входа"; exit 1; }
grep -rqs '\.grid{' "$APP/dist/assets/"*.css \
  || grep -rqs 'grid-template-columns' "$APP/dist/assets/"*.css \
  || { echo "ОШИБКА: в собранном CSS нет утилит tailwind — сборка внешне зелёная, но сломана"; exit 1; }
echo "ok: обе страницы на месте, tailwind в CSS есть"

# Публикация — синхронизацией ВНУТРЬ каталога, а не подменой каталога.
#
# Ровно здесь была ошибка, стоившая простоя: сначала скрипт собирал соседний
# `site.new` и переставлял каталоги через `mv`, что для файлов на диске
# выглядит безупречно и атомарно. Но `site` отдан контейнеру bind-монтом, а
# bind-монт привязан к inode, а не к пути: после перестановки контейнер
# продолжал держать СТАРЫЙ каталог, который скрипт тут же удалял. Наружу
# сайт отдавал 404 на всё, при этом на диске всё было правильно, а сборка
# рапортовала об успехе. Помогал только перезапуск контейнера.
#
# `rsync --delete` меняет содержимое, сохраняя сам каталог, поэтому монт
# остаётся живым и перезапуск не нужен. `--delete` обязателен: без него в
# `site/` накапливались бы ассеты всех прошлых сборок (у них имена с хешем,
# новые не перетирают старые).
echo "==> публикация в site/"
mkdir -p "$ROOT/site"
rsync -a --delete "$APP/dist/" "$ROOT/site/"

echo "==> готово: $(find "$ROOT/site" -type f | wc -l) файлов, $(du -sh "$ROOT/site" | cut -f1)"
echo "Перезапуск контейнера не нужен — caddy отдаёт файлы с диска."
