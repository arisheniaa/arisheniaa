#!/usr/bin/env bash
# СТОРОЖ ОБНОВЛЕНИЙ: новые коммиты в GitHub → пересборка сайта.
#
# Запускается таймером раз в 5 минут и в подавляющем большинстве запусков
# не делает ничего: спрашивает у GitHub хеш последнего коммита и молча
# выходит, если он совпадает с тем, что уже собрано. Это важно — `build.sh`
# поднимает контейнер и выполняет `npm ci` с полной сборкой, а на хосте
# 3.8 ГБ памяти, разделённых с другими проектами. Гонять такое раз в пять
# минут вхолостую нельзя.
#
# ПОЧЕМУ НЕ ВЕБХУК. Вебхук отдаёт обновление мгновенно, но требует открытого
# наружу обработчика, общего секрета и места в конфиге edge-прокси. Опрос
# раз в 5 минут не требует ничего: наружу этот сервер ничего не открывает,
# ключей на стороне GitHub не заводит. Задержка до пяти минут для сайта
# фотографа роли не играет.
#
# ПОЧЕМУ НЕ ТРОГАЕТ РАЗОШЕДШИЙСЯ КЛОН. Та же осторожность, что и в build.sh:
# если в клоне есть свои правки или коммиты, которых нет на origin, сторож
# ничего не собирает и пишет об этом в журнал. Ровно из-за такой ситуации
# 11 августа сайт три часа не обновлялся, и молчаливая перемотка тогда
# откатила бы правки, которых ещё не было в репозитории.

set -euo pipefail

ROOT=/opt/arisheniaa-site
REPO=$ROOT/repo

BRANCH=$(git -C "$REPO" rev-parse --abbrev-ref HEAD)
git -C "$REPO" fetch --quiet origin "$BRANCH"

LOCAL=$(git -C "$REPO" rev-parse HEAD)
REMOTE=$(git -C "$REPO" rev-parse FETCH_HEAD)

if [ "$LOCAL" = "$REMOTE" ]; then
  exit 0
fi

DIRTY=$(git -C "$REPO" status --porcelain)
if [ -n "$DIRTY" ]; then
  echo "В клоне есть незакоммиченные правки — сборку не запускаю."
  echo "Разберитесь вручную: git -C $REPO status"
  exit 0
fi

# `--is-ancestor` вместо сравнения счётчиков: работает и на неглубоком клоне,
# в который `build.sh` превращает репозиторий своим `fetch --depth 1`.
if ! git -C "$REPO" merge-base --is-ancestor HEAD FETCH_HEAD; then
  echo "Клон разошёлся с origin: здесь есть коммиты, которых нет на GitHub."
  echo "Сборку не запускаю, чтобы не откатить их молча."
  echo "Посмотреть: git -C $REPO log --oneline origin/$BRANCH..HEAD"
  exit 0
fi

# ЗАЩИТА СОСЕДЕЙ ПО ХОСТУ. На этой машине живут ещё два проекта: сайт
# uklonskiy и стек ORIION (postgres, redis, minio, backend, worker). Памяти
# 3.8 ГБ, а ПОДКАЧКИ НЕТ ВОВСЕ — при нехватке ядро не замедляет систему, а
# убивает процесс, выбирая жертву само.
#
# Лимит `-m 2g` в build.sh защищает соседей от самой сборки: при переборе
# умрёт контейнер сборки. Но эта проверка нужна для другого — не запускать
# сборку в момент, когда памяти мало УЖЕ СЕЙЧАС. Двухгигабайтная сборка
# вытеснит страничный кеш постгреса и редиса, и соседи просядут по скорости,
# даже никого не потеряв.
#
# Раньше сборку запускал человек и мог посмотреть на состояние машины.
# Сторож смотреть не умеет, поэтому смотрит за него эта проверка.
# Отложить ничего не стоит: следующая попытка через пять минут, а коммит
# никуда не денется.
AVAIL=$(awk '/MemAvailable/ {print int($2/1024)}' /proc/meminfo)
if [ "$AVAIL" -lt 2200 ]; then
  echo "Доступно памяти $AVAIL МБ — для сборки мало (нужно 2200)."
  echo "Отложил до следующей проверки, коммит не потеряется."
  exit 0
fi

echo "Новых коммитов: $(git -C "$REPO" rev-list --count "$LOCAL..$REMOTE"), памяти $AVAIL МБ. Пересобираю."
exec "$ROOT/build.sh"
