import { useEffect, useRef } from 'react';
import { onFrame } from './raf';

/**
 * ПОЛОТНО — меш-градиент на всю страницу. Лок, «Цвет»:
 *
 *  · не картинка-фон, а CSS-меш из радиальных слоёв. Цвета сняты пипеткой
 *    с файлов владелицы (значения и точки замера — в styles.css и README);
 *  · `position: fixed`, весь вьюпорт, слой под контентом;
 *  · реагирует на прокрутку: позиция и интенсивность слоёв идут за прогрессом;
 *  · зерно — SVG feTurbulence, тот же приём, что в B и C;
 *  · GSAP/Lenis в проект не возвращаются — прогресс считает один rAF на 40 строк.
 *
 * П7: при загрузке прогресс равен нулю и полотно стоит. Ни перехода, ни
 * проявления, ни мигания в первом кадре нет — движение начинается только
 * от прокрутки, то есть от действия читателя.
 *
 * prefers-reduced-motion: подписка на прокрутку не ставится вовсе, полотно
 * остаётся в стартовом положении. Контент от этого не теряется — полотно
 * декоративное и помечено aria-hidden.
 *
 * Почему rAF, а не обработчик scroll напрямую: обработчик стреляет чаще кадра
 * и заставляет перерисовывать полноэкранный слой по нескольку раз за кадр.
 * Значение округляется до 0.005 — при более мелком шаге браузер перекрашивает
 * полотно на каждый пиксель прокрутки без единого видимого изменения.
 *
 * ─── НАСТРОЕНИЕ ДИПТИХА (Ф29 п.1, FACTS.md — синтез
 * `RESEARCH-COMPETITORS.md` § 2, «не переключать секции резким блоком, а
 * вести CSS-переменные градиента непрерывно между «тихими» и «странными»
 * кадрами»; НЕ лок, расширение уже принятого решения). Вторая переменная,
 * `--mood`, — тот же принцип, что `--sp`, но ЛОКАЛЬНЫЙ прогресс: не всей
 * страницы, а прохода ОДНОЙ секции — диптиха «Как получается кино»
 * (`Cinema()` в `App.tsx`, помечен `data-mood-scope`). Если бы настроение
 * читало общий `--sp`, за короткий проход одной секции число почти не
 * сдвинулось бы (страница длинная, секция — её малая доля), и «переход между
 * тихим и странным именно здесь» на глаз не читался бы вовсе.
 *
 * 0 — верх диптиха ещё только показался у нижнего края экрана; 1 — низ
 * диптиха ушёл за верхний край. Слушатели — `.mesh-mood-a` / `.mesh-mood-b`
 * (styles.css): кроссфейд двух пятен вместо переключения, «свечение, а не
 * контраст» (`BRIEF.md`), тот же приём, что уже есть у свечения звёзд
 * (`Stars.tsx`), доведённый до света всей страницы.
 */
/**
 * `veil` — БЕЛОЕ ДЫХАНИЕ ПОЛОТНА, только ветка дизайна (Ф67, её слова:
 * «градиент должен медленно меняться на белый, а затем обратно в
 * зелено-желтый на протяжении всего лендинга»).
 *
 * Слой добавляется ВНУТРЬ полотна, а не отдельным узлом страницы, по одной
 * причине: прозрачность вуали считается из `--sp`, а `--sp` пишется на
 * `.canvas` (Ф45, чтобы пересчёт стиля не задевал весь документ) и
 * наследуется только вниз по её дереву. Снаружи переменная имела бы
 * значение из `:root`, то есть ноль всегда, и вуаль стояла бы неподвижно.
 *
 * Главной страницы это не касается: без пропа лишний узел не рендерится
 * вовсе, ни одного нового правила на фотографической ветке не появляется.
 */
export function Gradient({ veil = false }: { veil?: boolean } = {}) {
  const canvas = useRef<HTMLDivElement>(null);

  useEffect(() => {
    /* ═══ ПЕРЕМЕННЫЕ ПИШУТСЯ НА ПОЛОТНО, А НЕ НА КОРЕНЬ (Ф45) ═════════════
       `--sp` и `--mood` раньше ставились на `<html>`. Пользовательские
       свойства НАСЛЕДУЮТСЯ: изменение на корне помечает устаревшим стиль
       ВСЕГО документа — браузер обязан пересчитать стиль каждого узла на
       странице, чтобы убедиться, что его это не касается. Двести раз за
       проход страницы, при полутора тысячах узлов.
       Обе переменные читают ровно семь элементов, и все семь лежат внутри
       `.canvas`. Пишем туда — и пересчёт ограничен этими семью. */
    const root = canvas.current;
    if (!root) return;
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;

    const moodEl = document.querySelector<HTMLElement>('[data-mood-scope]');

    /* ═══ ЗАМЕРЫ РАСКЛАДКИ КЭШИРУЮТСЯ (Ф43) — «сайт ещё виснет» ══════════
       Прежний цикл на КАЖДОМ кадре читал `document.documentElement
       .scrollHeight` и `moodEl.getBoundingClientRect()`. Оба чтения —
       принудительный пересчёт раскладки: браузер обязан досчитать все
       отложенные изменения, прежде чем ответить. А отложенные изменения на
       этой странице были всегда: рядом в том же кадре шесть полей звёзд
       писали в DOM. Получался классический thrash — пишем, читаем, снова
       пишем, и каждое чтение заставляет пересчитать всё заново.
       Шестьдесят раз в секунду, всё время, независимо от того, шевелится ли
       страница вообще.

       НИ ОДНО ИЗ ЭТИХ ЧИСЕЛ НЕ МЕНЯЕТСЯ ОТ КАДРА К КАДРУ. Высота документа
       и положение диптиха В ДОКУМЕНТЕ (не на экране) постоянны, пока
       раскладка та же; от прокрутки меняется только `scrollY`. Поэтому оба
       меряются один раз и обновляются по `ResizeObserver` на `<body>` —
       то есть тогда, когда раскладка действительно поехала: догрузилась
       картинка, сменилась ориентация, раскрылась навигация.

       Положение секции на ЭКРАНЕ выводится арифметикой: `top = offsetTop −
       scrollY`. Это ровно то, что вернул бы `getBoundingClientRect`, но без
       единого обращения к раскладке.

       Плюс ранний выход: если прокрутка не сдвинулась с прошлого кадра,
       считать нечего вовсе. */
    let docOffset = 0;
    let moodTop = 0;
    let moodH = 0;

    const measure = () => {
      docOffset = document.documentElement.scrollHeight - window.innerHeight;
      if (moodEl) {
        const r = moodEl.getBoundingClientRect();
        moodTop = r.top + window.scrollY; // положение в документе, не на экране
        moodH = r.height;
      }
    };
    measure();

    const ro = new ResizeObserver(measure);
    ro.observe(document.body);

    let last = -1;
    let lastMood = -1;
    let lastScroll = -1;

    const tick = () => {
      const sy = window.scrollY;
      if (sy === lastScroll) return; // страница стоит — считать нечего
      lastScroll = sy;

      const p = docOffset > 0 ? Math.min(1, Math.max(0, sy / docOffset)) : 0;
      const q = Math.round(p * 200) / 200;
      if (q !== last) {
        last = q;
        root.style.setProperty('--sp', String(q));
      }

      if (moodEl) {
        const vh = window.innerHeight;
        const top = moodTop - sy; // то же, что r.top, но без чтения раскладки
        const raw = (vh - top) / (vh + moodH);
        const mood = Math.min(1, Math.max(0, raw));
        const qm = Math.round(mood * 200) / 200;
        if (qm !== lastMood) {
          lastMood = qm;
          root.style.setProperty('--mood', String(qm));
        }
      }
    };

    const stopFrames = onFrame(tick);
    return () => {
      stopFrames();
      ro.disconnect();
    };
  }, []);

  return (
    <div className="canvas" aria-hidden="true" ref={canvas}>
      {/* Ф45: пять пятен вместо двух слоёв. Пятна ездят в разные стороны, а
          один `transform` на слой умеет двигать только всё разом — значит
          каждому нужен свой слой. Зато движение теперь composited: слой
          растрируется один раз и дальше просто сдвигается, вместо
          перерисовки полутора экранов градиентов на каждом шаге прокрутки.
          Подробности и прежние формулы — `.mesh-spot` в `styles.css`. */}
      <div className="mesh-spot mesh-s1" />
      <div className="mesh-spot mesh-s2" />
      <div className="mesh-spot mesh-s3" />
      <div className="mesh-spot mesh-b1" />
      <div className="mesh-spot mesh-b2" />
      {/* Настроение диптиха — прозрачность по `--mood`, перерисовки не
          вызывает (см. комментарий у `.mesh-mood-a`), поэтому слои прежние. */}
      <div className="mesh mesh-mood-a" />
      <div className="mesh mesh-mood-b" />
      {/* Белое дыхание ветки дизайна — см. шапку функции. Последним узлом:
          вуаль обязана лежать поверх всех пятен, иначе белила бы не
          полотно, а пустоту под ним. */}
      {veil ? <div className="mesh mesh-veil" /> : null}
    </div>
  );
}

/**
 * Зерно. Отдельным фиксированным слоем ПОВЕРХ контента, а не по секциям, как
 * было в B: у нас под всем лежит одно непрерывное полотно, и зерно, нарезанное
 * по секциям, давало бы видимые швы на стыках. Лежит и на фотографиях тоже —
 * стерильных пикселей на этом сайте нет нигде.
 */
export function Grain() {
  return <div className="grain-veil" aria-hidden="true" />;
}
