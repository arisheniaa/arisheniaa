import { useState } from 'react';

/**
 * ДЕМОНСТРАЦИЯ ОТДАЧИ (лок, «Демонстрация отдачи материала», Ф25).
 * Одна папка с подписью «нажми на меня» → клик → две дочерние папки одного
 * цвета с подписями «на цифру» и «на плёнку». Иллюстрирует факт Ф1 (диск, при
 * плёнке две папки) интерфейсом, а не текстом. Дочерние декоративны — это
 * демонстрация организации отдачи, не файловый менеджер.
 *
 * Все три подписи — дословно, строчными. Подписи дочерних папок — `COPY.md`
 * ред. 6 § 1.6.1; подпись-триггер и пояснение под демонстрацией — Ф28.
 *
 * РЕДАКЦИЯ 2 (Ф28): подпись-триггер «нажми на меня» переехала НА саму папку
 * («текст „нажми на меня“ сделай на самой папке»), пояснение заменено словами
 * владелицы. Анимация раскрытия не тронута — Ф28 прямо: «и ту же анимацию».
 * Цвет папки больше не зависит от темы: тема одна (Ф28), `папка2.jpg`
 * (бордовая, для розовой темы) в работе не участвует.
 *
 * ПАПКА НАРИСОВАНА, А НЕ ВСТАВЛЕНА КАРТИНКОЙ — и это отклонение от буквы Ф24
 * («ассеты: папка.jpg, папка2.jpg»), заявленное по правилу П3:
 *   что запрещаю — `папка.jpg` и `папка2.jpg` как <img>;
 *   чем заменяю — та же папка в SVG, цвета сняты пипеткой с этих двух файлов;
 *   почему — оба файла это JPG с белым фоном 500×500. Поверх сплошного
 *   градиентного полотна белый квадрат вокруг папки виден сразу, а вырезать
 *   фон из JPG значит получить кайму. И главное: лок требует, чтобы «цвет папок
 *   зависел от активной темы» — растровая картинка тему не слышит, а путь SVG
 *   красится переменной. Файлы остались источником формы и цвета, они не
 *   выброшены; выброшен только способ доставки пикселей.
 *
 * Пипетка по файлам владелицы:
 *   папка.jpg  — тело #AEB883, отворот #767A5F (оливковая, зелёная тема);
 *   папка2.jpg — тело #882043 (бордовая, розовая тема), отворот темнее на 12 %.
 * Значения живут в теме как --folder-face / --folder-back.
 *
 * П7: в первом кадре этого блока нет вовсе — он ниже сгиба, и всё его движение
 * отвечает на клик. prefers-reduced-motion: раскрытие мгновенное, без съезда,
 * обе дочерние папки на месте и подписаны.
 *
 * АСИММЕТРИЧНЫЙ РАЗЛЁТ (Ф29 п.7, FACTS.md — синтез `RESEARCH-COMPETITORS.md`
 * § 3, «асимметричный разлёт читается как настоящие, а не как сгенерированная
 * иконка... сдвиг на несколько градусов по углу и лёгкая разница в скорости»;
 * НЕ лок, усиление Ф25). Раньше обе дочерние папки раскрывались ОДНОЙ и той
 * же формулой transform, различаясь только 70-мс сдвигом таймера. Теперь
 * угол, сдвиг по X, масштаб и сама длительность перехода у «на цифру» и «на
 * плёнку» разные — реализовано в `styles.css` через `:nth-child(1)`/`(2)`
 * на `.delivery-children > .folder`, не формулой от переменной `--n`: два
 * ручных набора чисел ближе к «неровно рукой», чем производная одной
 * переменной, которая всё равно осталась бы симметричной функцией индекса.
 */

function FolderShape({ className = '' }: { className?: string }) {
  return (
    <svg viewBox="0 0 100 82" className={className} aria-hidden="true" focusable="false">
      {/* задняя половина с отворотом — по силуэту `папка.jpg` */}
      <path
        d="M4 12a8 8 0 0 1 8-8h22l12 9h38a8 8 0 0 1 8 8v53a8 8 0 0 1-8 8H12a8 8 0 0 1-8-8z"
        fill="var(--folder-back)"
      />
      {/* передняя створка */}
      <path
        d="M4 26a8 8 0 0 1 8-8h76a8 8 0 0 1 8 8v44a8 8 0 0 1-8 8H12a8 8 0 0 1-8-8z"
        fill="var(--folder-face)"
      />
    </svg>
  );
}

export function DeliveryDemo({
  trigger,
  digital,
  film,
  note,
}: {
  trigger: string;
  digital: string;
  film: string;
  note: string;
}) {
  const [open, setOpen] = useState(false);

  return (
    <div className="delivery">
      <div className="delivery-stage" data-open={open ? '' : undefined}>
        {/* Родительская папка. Кнопка, а не div с onClick: её надо доставать
            клавиатурой, и она должна сообщать своё состояние. */}
        <button
          type="button"
          className="folder folder-parent"
          onClick={() => setOpen((v) => !v)}
          aria-expanded={open}
          aria-controls="delivery-children"
        >
          {/* Ф28: подпись-триггер лежит НА самой папке, а не строкой под ней.
              Текст остаётся текстом в DOM (П8) — он не превратился в часть
              картинки, просто переехал внутрь предмета. */}
          <span className="folder-art-wrap">
            <FolderShape className="folder-art" />
            <span className="folder-trigger-label">
              <span>{trigger}</span>
            </span>
          </span>
        </button>

        {/* Дочерние. Всегда в разметке: контент не должен появляться из ничего
            для поиска и скринридера, поэтому скрывается не наличием узла,
            а состоянием, и в reduced-motion просто стоит на месте. */}
        <ul id="delivery-children" className="delivery-children" data-open={open ? '' : undefined}>
          {/* Порядок в массиве определяет `:nth-child` в CSS (Ф29 п.7):
              первая — «на цифру», вторая — «на плёнку», у каждой свой угол,
              сдвиг, масштаб и длительность раскрытия — см. `styles.css`. */}
          {[digital, film].map((label) => (
            <li key={label} className="folder folder-child">
              <FolderShape className="folder-art" />
              <span className="folder-label">{label}</span>
            </li>
          ))}
        </ul>
      </div>

      <p className="t-body mt-[clamp(1.4rem,3vw,2.2rem)] max-w-[30ch] text-[color:var(--ink-soft)]">
        {note}
      </p>
    </div>
  );
}
