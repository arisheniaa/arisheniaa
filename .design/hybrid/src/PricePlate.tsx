/**
 * ПЛАШКА ЦЕНЫ — СКРЫТА В ПОКОЕ, ВОЗНИКАЕТ ПРИ НАВЕДЕНИИ НА КАРТОЧКУ (Ф40).
 *
 * Дословно владелицы: «блок с ценой (вместе с городами и часами) должен
 * плавно возникать при наведении курсора на тип съемки/услуги». Четвёртая
 * редакция механики:
 *   · Ф29 п.6 — цифра приглушена `blur`, открывалась ПО КЛИКУ;
 *   · Ф36 п.8 — «чтобы было сразу видно стоимость и город»: открывалась сама
 *     при входе секции в кадр;
 *   · Ф39 — закрыта, наведение НА ПЛАШКУ открывало только цифры;
 *   · Ф40 — прячется и появляется ПЛАШКА ЦЕЛИКОМ, наводить надо на карточку.
 *
 * ЧТО ИЗ ЭТОГО СЛЕДУЕТ ДЛЯ ЭТОГО ФАЙЛА. Он стал тривиальным, и это правка,
 * а не упущение. Раньше здесь жил `splitPrice()`: строка резалась регулярным
 * выражением на «денежные» куски и всё остальное, чтобы «дверца» могла
 * открыть цифры, оставив город видимым. Теперь скрывается весь блок разом —
 * резать нечего, и весь разбор снят вместе с классом `price-plate-digits`.
 * Держать мёртвый парсер «на случай возврата» было бы хуже: он читался бы
 * как работающий механизм.
 *
 * ВСЯ МЕХАНИКА — В CSS (`styles.css`, «ПЛАШКА ЦЕНЫ»): `opacity` +
 * `visibility` + сдвиг, область наведения — `.offer-card`. Здесь JS нет и не
 * было ни в одной из четырёх редакций.
 *
 * НЕ `<button>`: нажимать нечего, реагирует наведение. Кнопка, на которую
 * нельзя нажать, была бы враньём разметки.
 *
 * ТЕКСТ В DOM СТОИТ ВСЕГДА, целиком и посимвольно (правило «боевой текст
 * дословно» — зона `home:offer.card.*.price` в COPY одна строка, версии
 * «без цифры» там нет). Скрытие визуальное; `visibility` возвращается тем же
 * переходом, что и `opacity`, — см. комментарий в CSS.
 *
 * ТАЧ (правка билдера, не в FACTS.md — см. сообщение коммита). На вводе без
 * курсора (`@media (hover: none)`) наводить курсором нечем, поэтому плашка
 * открывается по факту «карточка услуги целиком на экране» — тот же
 * переход, что у `:hover`, только триггер ставит/снимает
 * `usePriceReveal()` (`reveal.ts`, `IntersectionObserver`) атрибутом
 * `data-in-view` на `.offer-card`, а не движение курсора. При выключенном
 * движении (`prefers-reduced-motion: reduce`) хук не подключается вовсе, и
 * CSS возвращает плашку к «видна всегда, статично» — см. `styles.css`,
 * оба блока рядом с `.price-plate`.
 *
 * КРЮЧОК СЪЁМКИ `?priceplate=closed` — форсирует скрытое состояние через
 * `data-force-closed`. Нужен потому, что `Locator.hover()` в скрипте съёмки
 * доказательств наводит курсор сам, и «кадр закрытого состояния» без крючка
 * мог бы снять уже открытое. На продукт не влияет, в продуктовом пути
 * параметра нет (см. `scripts/shots.mjs`).
 */
const FORCE_CLOSED = (() => {
  if (typeof location === 'undefined') return false;
  return new URLSearchParams(location.search).get('priceplate') === 'closed';
})();

export function PricePlate({ text }: { text: string }) {
  return (
    <span className="plate t-num price-plate" data-force-closed={FORCE_CLOSED ? '' : undefined}>
      {text}
    </span>
  );
}
