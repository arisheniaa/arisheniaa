import { Fragment } from 'react';

/**
 * ПЛАШКА ЦЕНЫ — ОТКРЫТА СРАЗУ (Ф36 п.8, FACTS.md — ОТМЕНА решения Ф29 п.6).
 *
 * Дословно владелицы: «сделай плашку как дверцу, открывающуюся снизу вверх,
 * чтобы было сразу видно стоимость и город, а не только город». Раньше
 * (редакция 3, Ф29 п.6) цифра была приглушена `blur` и ждала клика — она
 * прямо это отменяет: конечное состояние покоя обязано показывать цену
 * ОТКРЫТО, без клика. Поэтому `.price-plate` больше не `<button>` —
 * открывать по клику нечего, а некликабельная кнопка была бы отдельным
 * нарушением (интерактивный элемент обязан что-то делать).
 *
 * «ДВЕРЦА, ОТКРЫВАЮЩАЯСЯ СНИЗУ ВВЕРХ» — реализована `clip-path`, не заново
 * написанной анимацией (правило «движение из примитивов»): триггер — тот же
 * `.reveal`/`is-sharp`, что уже двигает всю остальную страницу (`reveal.ts`,
 * IntersectionObserver + CSS-переход). Нового JS нет вовсе — только новое
 * CSS-правило на уже существующий переключатель класса (`styles.css`,
 * `.reveal.is-sharp .price-plate-digits`). Закрытое состояние —
 * `clip-path: inset(100% 0 0 0)` (видимая область нулевой высоты, прижата
 * к верхнему краю), открытое — `clip-path: none`: видимая граница уезжает
 * вверх, обнажая цифры снизу вверх, один раз, когда плашка входит в кадр
 * при прокрутке — ровно так же, как остальной контент секции.
 *
 * ПОЧЕМУ ЦИФРА ВСЁ РАВНО НЕ ВЫРЕЗАНА ИЗ ТЕКСТА. Правило «боевой текст
 * дословно» запрещает резать и переписывать `COPY.md` под макет. Зона
 * `home:offer.card.*.price` — ОДНА строка целиком, в COPY нет отдельной
 * «версии без цифры». В DOM всегда стоит ПОЛНАЯ строка посимвольно — «дверца»
 * это исключительно визуальный слой поверх текста (`clip-path`), тот же
 * приём, что уже применён к капители служебного слоя (README § 4 п. 6).
 * `clip-path` не прячет содержимое от скринридера (чисто визуальный эффект,
 * как раньше `filter: blur`) — доступность бесплатно, цена озвучивается
 * сразу независимо от того, докрутил ли посетитель до неё глазами.
 *
 * КРЮЧОК СЪЁМКИ `?priceplate=closed` — находка при первой съёмке доказательств:
 * `Locator.screenshot()` в Playwright сам прокручивает элемент во вьюпорт ПЕРЕД
 * кадром, а прокрутка — ровно то действие, которое открывает дверцу. «Кадр
 * закрытого состояния» без крючка на самом деле снимал уже открытое — дверцу
 * физически нельзя увидеть закрытой в кадре, где она же видна целиком, без
 * скролла к ней вручную с паузой ДО перехода. Тот же класс находки, что уже
 * был у рэка (`useRack.ts`, `?rack=`): у headless-браузера нет «просто
 * посмотреть, не долистывая». Крючок форсирует закрытое состояние через
 * `data-force-closed` независимо от `.reveal`/`is-sharp` — на продукт не
 * влияет, в продуктовом пути параметра нет (см. `scripts/shots.mjs`).
 */
const FORCE_CLOSED = (() => {
  if (typeof location === 'undefined') return false;
  return new URLSearchParams(location.search).get('priceplate') === 'closed';
})();

/** Матчит денежные куски строки: цифры, неразрывные пробелы-разделители
 *  тысяч (U+00A0, набран юникод-эскейпом, а не литералом — литерал невидим
 *  в дифе и в редакторе, эскейп читается глазами) и сам знак валюты. */
const PRICE_RE = /[\d\u00A0]+₽/g;

function splitPrice(s: string): { text: string; price: boolean }[] {
  const out: { text: string; price: boolean }[] = [];
  let last = 0;
  let m: RegExpExecArray | null;
  PRICE_RE.lastIndex = 0;
  while ((m = PRICE_RE.exec(s))) {
    if (m.index > last) out.push({ text: s.slice(last, m.index), price: false });
    out.push({ text: m[0], price: true });
    last = m.index + m[0].length;
  }
  if (last < s.length) out.push({ text: s.slice(last), price: false });
  return out;
}

export function PricePlate({ text }: { text: string }) {
  const segments = splitPrice(text);

  return (
    <span className="plate t-num price-plate">
      {segments.map((seg, i) =>
        seg.price ? (
          <span
            key={i}
            className="price-plate-digits"
            data-force-closed={FORCE_CLOSED ? '' : undefined}
          >
            {seg.text}
          </span>
        ) : (
          <Fragment key={i}>{seg.text}</Fragment>
        ),
      )}
    </span>
  );
}