/**
 * БАЗОВЫЙ ПУТЬ САЙТА — один на весь код (переезд на `/ph`, 3 октября 2026).
 *
 * Решение владелицы: корень `arisheniaa.ru` отдаётся новому сайту дизайнера,
 * а фото-сайт переезжает в `arisheniaa.ru/ph/` без единого изменения в виде
 * и тексте. Префикс задан ОДИН раз — `base: '/ph/'` в `vite.config.mts`, —
 * а сюда приходит готовым через `import.meta.env.BASE_URL`.
 *
 * ПОЧЕМУ НЕ ПРОСТО «ДОПИСАТЬ /ph В КАЖДУЮ СТРОКУ». Vite сам переписывает
 * только то, что видит при сборке: импорты, `url()` в CSS, ссылки в
 * `<head>` HTML-входов. Пути-СТРОКИ в коде (`'/frames/x.webp'` в `copy.ts`,
 * `fetch('/storyboard/manifest.json')`, `href="/#uslugi"`) для него просто
 * текст — они уезжают в сборку как есть и после переезда смотрят в корень
 * домена, то есть на ЧУЖОЙ сайт. Зашитый `/ph` в сорока местах сломался бы
 * так же при следующем переезде; одна функция переносится одной строкой
 * конфига.
 *
 * Правило для нового кода: любой путь к файлу из `public/` или к странице
 * этого сайта — через `asset()`. Голый `'/…'` в `src/` — ошибка, которую
 * не видно в dev на старом адресе и видно только после выкладки.
 */

/** Префикс сайта с завершающим слэшем: `'/ph/'` (в dev и в сборке одинаково). */
export const BASE: string = import.meta.env.BASE_URL;

/**
 * Путь внутри сайта → адрес с префиксом: `asset('frames/x.webp')` →
 * `'/ph/frames/x.webp'`, `asset('#uslugi')` → `'/ph/#uslugi'`.
 *
 * Ведущий слэш у аргумента допускается и срезается: так старые записи
 * вида `'/storyboard/sb-….webp'` (манифест, собранный до переезда) дают
 * верный адрес, а не `'/ph//storyboard/…'` с двойным слэшем.
 */
export function asset(path: string): string {
  return BASE + path.replace(/^\/+/, '');
}
