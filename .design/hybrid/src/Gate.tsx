/**
 * РАЗВИЛКА «СЪЁМКА / САЙТ» — HERO-БЛОК ГЛАВНОЙ (Ф67, перестроен Ф72).
 *
 * Владелица: «развилку сделай hero блоком, а при выборе направления, нужное
 * должно тематически отрисовываться под hero блоком»; «тот же адрес, без
 * перехода»; до выбора — «просто экран без возможности скролла»; при выборе
 * развилка «уезжает вверх совсем».
 *
 * КАК УСТРОЕНО. Развилка занимает весь экран и держит прокрутку запертой,
 * пока человек не выбрал. Выбор не уводит никуда: `App.tsx` меняет ветку
 * ПОД шторой, пока та ещё закрывает экран, и только потом штора уезжает
 * вверх. Поэтому обе ветки открываются одинаково — одним движением, без
 * перезагрузки и без второго адреса.
 *
 * ВЫБОР ПИШЕТСЯ В АДРЕС отдельным шагом истории (`#photo` / `#design`):
 * обновление страницы держит выбранную ветку, а «назад» возвращает к
 * развилке. Логику адреса держит `App.tsx` — здесь только показ и уход.
 *
 * КОГДА РАЗВИЛКИ НЕТ: адрес с любым якорем. Это и внутренние ссылки
 * (`/#uslugi`), и метки веток, и перенаправление со старого `/design.html`
 * на `/#design`. Человек, пришедший В МЕСТО на странице, не должен
 * получать вопрос, на который он уже ответил.
 *
 * ДОСТУПНОСТЬ. Пока штора стоит, соседям по дереву ставится `inert`: табом
 * нельзя уйти в контент, которого не видно. Прокрутка на это время заперта.
 * При `prefers-reduced-motion` штора снимается без движения.
 */
import { useEffect, useRef, useState } from 'react';
import { copy } from './copy';
/* `Stars` не импортируются с правки «убери звездочки» (второе сообщение
   Ф67) — развилка единственное место сайта, где россыпи быть не должно. */
import { Name } from './Name';

/* КАДР РАЗВИЛКИ ДЛЯ ТЕЛЕФОНА. Владелица прислала два снимка и выбрала
   первый: `gate-a.webp` — IMG_0852. Второй (`gate-b`) можно вернуть правкой
   этой строки и одной командой экспорта (`scripts/export-gate-photo.mjs`).
   Раскладка, затемнение и тексты от снимка не зависят. */
const GATE_PHOTO = '/gate/gate-a.webp';

/* Хранилища сессии здесь больше нет. Состояние развилки целиком живёт в
   АДРЕСЕ (`#photo` / `#design` / пусто), и это лучше по трём причинам:
   ссылку можно переслать, «назад» работает сам собой, а приватный режим
   браузера ничего не ломает. Прежние ключи (`gate-f67`, `gate-f67-drop`)
   удалены вместе с отдельной страницей дизайна, ради передачи на которую
   второй ключ и заводился. */

const reduceMotion = () =>
  typeof window !== 'undefined' &&
  window.matchMedia('(prefers-reduced-motion: reduce)').matches;

export function Gate({
  onChoose,
  onGone,
}: {
  /** Вызывается СРАЗУ по нажатию, пока штора ещё закрывает экран: ветка под
   *  ней успевает смениться незаметно. */
  onChoose: (branch: 'photo' | 'design') => void;
  /** Штора доехала и снята из дерева — можно забыть о ней. */
  onGone: () => void;
}) {
  /* Штора всегда рождается поднятой. Решение, показывать ли её вообще,
     принимает `App.tsx` по адресу: нет якоря — рендерит развилку, есть —
     не рендерит. Здесь состояний три: стоит, уезжает, снята. */
  const [state, setState] = useState<'up' | 'away' | 'gone'>('up');
  const node = useRef<HTMLDivElement>(null);

  /* Пока штора стоит — прокрутка заперта, а всё, что лежит под ней, глохнет
     для клавиатуры и скринридера.

     `inert` СТАВИТСЯ НА ВСЕХ СОСЕДЕЙ ШТОРЫ ПО ДЕРЕВУ, а не на список
     `header, main, footer`, как было в первой версии. Причина найдена
     обходом табом, а не рассуждением: третьим и четвёртым нажатием фокус
     уходил на кнопки бокового указателя разделов (`SectionStars`,
     `.section-stars`) — тот рендерится в `Page()` СОСЕДОМ шапки и main, а
     не внутри них, и перечисление лендмарков его не накрывало. То есть с
     развилки можно было уйти клавиатурой в навигацию по невидимому сайту.

     Перебор соседей закрывает и любой будущий слой, который поставят рядом:
     список тегов пришлось бы дописывать руками, а про это забывают. Сама
     штора из перебора исключена — иначе оглохла бы вместе со страницей.
     Полотно и зерно (`aria-hidden`) от `inert` ничего не теряют. */
  useEffect(() => {
    if (state !== 'up') return;
    const doc = document.documentElement;
    const prev = doc.style.overflow;
    doc.style.overflow = 'hidden';

    const self = node.current;
    const parent = self?.parentElement;
    /* Помним ровно то, что заглушили сами: снимать `inert` в конце нужно
       только со своих узлов. Чужой `inert`, если он когда-нибудь появится,
       не наш и трогать его нельзя. */
    const muted = new Set<Element>();
    const mute = () => {
      if (!parent) return;
      for (const el of Array.from(parent.children)) {
        if (el === self || el.hasAttribute('inert')) continue;
        el.setAttribute('inert', '');
        muted.add(el);
      }
    };
    mute();

    /* НАБЛЮДАТЕЛЬ ОБЯЗАТЕЛЕН, и это находка обхода табом, а не
       предосторожность впрок. Разовый список соседей закрывал не всё:
       боковой указатель разделов (`SectionStars`) считает секции в своём
       эффекте и до первого счёта не даёт узла вовсе — в дерево он попадает
       ВТОРЫМ проходом, уже после того, как штора расставила `inert`. В
       итоге третьим нажатием таба фокус уходил на «Раздел 1 из 7» —
       навигацию по сайту, которого не видно. Наблюдатель глушит и тех, кто
       появился позже. */
    const mo = parent ? new MutationObserver(mute) : null;
    mo?.observe(parent!, { childList: true });

    return () => {
      mo?.disconnect();
      doc.style.overflow = prev;
      muted.forEach((el) => el.removeAttribute('inert'));
    };
  }, [state]);

  /* Снятие из дерева — по концу перехода transform, а не таймером той же
     длительности: таймер разойдётся с CSS при первой же правке 900 мс.
     Страховка на случай, когда `transitionend` не придёт вовсе (вкладка в
     фоне, старый браузер), — тоже есть, с запасом к CSS-длительности. */
  useEffect(() => {
    if (state !== 'away') return;
    const el = node.current;
    /* Фильтр по цели и свойству ОБЯЗАТЕЛЕН: `transitionend` всплывает, и
       без него первым до обработчика долетал конец перехода нажатой ссылки
       (у `.link-major` переход подчёркивания и нажатия) — штора снималась
       из дерева через десятки миллисекунд после клика, БЕЗ движения. Поймано
       замером transform по таймлайну, не глазами: кадр «вроде уехала» и кадр
       «исчезла мгновенно» на скриншоте неотличимы. */
    const done = (e?: TransitionEvent) => {
      if (e && (e.target !== el || e.propertyName !== 'transform')) return;
      setState('gone');
      onGone();
    };
    const fallback = () => {
      setState('gone');
      onGone();
    };
    el?.addEventListener('transitionend', done as EventListener);
    const t = window.setTimeout(fallback, 1400);
    return () => {
      el?.removeEventListener('transitionend', done as EventListener);
      window.clearTimeout(t);
    };
  }, [state]);

  if (state === 'gone') return null;

  const выбрать = (branch: 'photo' | 'design') => (e: React.MouseEvent) => {
    /* Модифицированный клик (Ctrl/Cmd/Shift/средняя кнопка) не
       перехватывается: человек просил новую вкладку — ссылки настоящие
       (`/#photo`, `/#design`), пусть браузер их и откроет. */
    if (e.defaultPrevented || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
    e.preventDefault();
    /* Ветка меняется ПЕРВОЙ, пока штора ещё закрывает экран: подмена
       происходит за ней и в кадр не попадает. Уход — следом. */
    onChoose(branch);
    setState(reduceMotion() ? 'gone' : 'away');
    if (reduceMotion()) onGone();
  };

  return (
    <div ref={node} className={`gate ${state === 'away' ? 'is-away' : ''}`}>
      {/* ═══ КОМПОЗИЦИЯ, РЕДАКЦИЯ 4 (Ф67) ═══════════════════════════════════
          Владелица: «"хочу съемку" и "хочу сайт" сделай на предыдущем уровне.
          а на мобильной версии уменьши фотографию до размера оригинала, сразу
          под фотографией сделай подпись-текст, а еще ниже в одну строчку две
          ссылки».

          ДВЕ РАЗНЫЕ КОМПОЗИЦИИ ИЗ ОДНОЙ РАЗМЕТКИ, разводятся стилями
          (styles.css, блок `.gate-stage`):
           · широкий экран — кадр во весь экран под всем остальным, текст
             прижат к низу, двери висят на середине высоты у левого и правого
             края. «На предыдущем уровне» — это оно: там они и стояли, пока
             текст не уехал вниз и не утащил их за собой;
           · телефон — кадр целиком, своей пропорцией, без обрезки; под ним
             текст, под текстом обе двери одной строкой.

          Порядок узлов — имя, кадр, текст, двери — совпадает с телефонной
          раскладкой один в один, поэтому клавиатура и скринридер идут в том
          же порядке, в каком читает глаз. На широком экране из потока
          выходят только кадр, затемнение и двери; порядок чтения не
          меняется. */}
      <div className="gate-stage">
        <div className="gate-head">
          <Name />
        </div>

        {/* Кадр — тот же портрет, что в «Кто снимает» (обоснование выбора у
            зоны `copy.gate`). Без `data-focus` и без `reveal`: под шторой
            прокрутки нет, а наводка на резкость считает позицию именно от
            неё — кадр остался бы размытым навсегда (поймано на живой
            странице). `width`/`height` заданы, чтобы место под кадр было
            известно заранее и телефонная раскладка не прыгала, когда он
            догрузится. */}
        {/* ДВА РАЗНЫХ КАДРА ПОД ДВЕ ФОРМЫ ЭКРАНА, выбирает браузер.

            Телефон получает ВЕРТИКАЛЬНЫЙ снимок (846×1280 в исходнике,
            `scripts/export-gate-photo.mjs`), широкий экран — прежний
            горизонтальный портрет из «Кто снимает». Причина не во вкусе:
            горизонтальный кадр 3:2 на вертикальном экране обрезается до
            середины лица, и никакой вёрсткой это не лечится — это
            арифметика пропорций. Владелица дала снимки, снятые вертикально,
            и вопрос закрылся сам.

            `<picture>` вместо двух `<img>` с `display:none`: браузер
            скачивает ТОЛЬКО подходящий файл. Два тега грузили бы оба, то
            есть телефон тянул бы лишние сотни килобайт по мобильной сети —
            ровно тому, ради кого всё это и делается.

            `alt=""`: описание портрета несёт `copy.about.alt`, и на этой
            странице оно уже прочитано — фоновый кадр декоративен. */}
        <picture>
          <source media="(min-width: 768px)" srcSet={copy.about.photo} />
          <img
            className="gate-photo"
            src={GATE_PHOTO}
            width={900}
            height={1362}
            alt=""
            aria-hidden="true"
            decoding="async"
          />
        </picture>
        <div className="gate-shade" aria-hidden="true" />

        <section aria-label="Съёмка или сайт" className="gate-body">
          {/* ЧЁТКАЯ КОПИЯ КАДРА СНЯТА. Она стояла здесь, пока телефон
              показывал горизонтальный снимок: тот не ложился на
              вертикальный экран, и его показывали карточкой поверх
              размытой копии. С вертикальным кадром подпорка не нужна —
              «фотографию размести так же, как это выглядит на десктопе»:
              снимок занимает весь экран, текст и двери лежат на нём.
              Правило `.gate-portrait` в styles.css удалено вместе с узлом. */}
          {/* Один абзац с явным переносом, а не два: фраза у неё одна, и
              скринридер должен прочесть её одной репликой, без паузы между
              «предложениями». `<br />` даёт разрыв только глазу. */}
          <p className="reveal t-h2 gate-text">
            {copy.gate.hello}
            <br />
            {copy.gate.helloTail}
          </p>

          {/* `whitespace-nowrap` у обеих: на широком экране «хочу съемку»
              ломалось на две строки, и двери вставали на разной высоте
              (замерено: 422 против 440 px). Подписи короткие, переносить в
              них нечего. */}
          <div className="gate-doors reveal" style={{ ['--i' as string]: 1 }}>
            <a
              className="link-major link-tap t-h3 whitespace-nowrap"
              href="/#photo"
              onClick={выбрать('photo')}
            >
              {copy.gate.photo}
            </a>
            <a
              className="link-major link-tap t-h3 whitespace-nowrap"
              href="/#design"
              onClick={выбрать('design')}
            >
              {copy.gate.design}
            </a>
          </div>
        </section>
      </div>
    </div>
  );
}
