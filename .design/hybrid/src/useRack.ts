import { onFrame } from './raf';
import { useCallback, useEffect, useRef, useState } from 'react';
import type { RefObject } from 'react';

/**
 * РЭК — механика удержания внимания первого экрана (правило П13).
 *
 * Два кадра лежат в одной руке: тихое сверху, странное под ним, нижний
 * выглядывает из-под верхнего на 15 px — это статичная подсказка, что стопка
 * настоящая, и она не требует ни движения при загрузке, ни строчки пояснения.
 * Верхний кадр берётся пальцем или курсором и тянется 1:1. Отпустили слабо —
 * пружина возвращает домой; бросили — импульс проецируется вперёд, кадр уходит
 * за край и возвращается уже снизу стопки, а сверху оказывается второй.
 *
 * Зачем именно это: гейт 1 требует, чтобы оба регистра автора существовали
 * с первого экрана. Здесь они существуют не как два заголовка, а как один
 * предмет, который читатель держит и переворачивает сам.
 *
 * Физика — по apple-design, числами:
 *  · слежение 1:1 с сохранением точки захвата (Pointer Events + setPointerCapture);
 *  · вертикаль следует на 0.35 с резиновым сопротивлением (rubberband, c = 0.55);
 *  · проекция импульса — экспоненциальная, decelerationRate 0.996
 *    (не 0.998: бросок здесь длиной в карточку, а не в страницу);
 *  · порог переворота — проекция за 34 % ширины карточки, решает знак скорости;
 *  · возврат домой — пружина damping 1.00, response 0.52 c (без овершута);
 *  · бросок — damping 1.00, response 0.52 c, скорость пальца гасится до 0.45;
 *  · возврат из-за стопки — damping 1.00, response 0.66 c;
 *
 * ═══ ТРИ ЧИСЛА СМЯГЧЕНЫ (Ф61) ═══════════════════════════════════════════
 * Владелица: «на мобильной версии слишком резкая прокрутка стопки
 * фотографий на главной. сделай её плавной».
 *
 * СНАЧАЛА ПРОВЕРИЛ, НЕ РЫВОК ЛИ ЭТО. Покадровый замер во время смахивания и
 * после него: в худшем кадре после отпускания двигается РОВНО ОДИН слой, на
 * 16,8 px — это летящий кадр. Разрыва, при котором вся стопка перескакивает
 * разом (например от смены глубины у всех карточек в один кадр), нет:
 * порогов выше 6 px за кадр у остальных слоёв не нашлось ни одного. Значит
 * чинить нечего — вопрос в скорости, а не в дефекте, и правка вкусовая.
 *
 * ЧИСЛА ПОДОБРАНЫ ЗАМЕРОМ, А НЕ НА СЛУХ, и первая попытка была неверной.
 * Сначала я удлинил пружину броска (0.38 → 0.54 c) — и пиковая скорость
 * ВЫРОСЛА. Причина в самом уравнении: `w = 2π/response` входит и в
 * возвращающую силу, и в торможение (`2·w·damping·v`). Удлиняя отклик, я
 * ослабил не только притяжение к цели, но и вязкость, и скорость, влитая
 * броском пальца, стала жить дольше. Плавность здесь задаётся не одним
 * числом, а парой «отклик + сколько импульса вообще впустить».
 *
 * Прогон пяти наборов на ДЕТЕРМИНИРОВАННОМ входе (кнопка «следующий кадр»:
 * у неё скорость задана числом, а не пальцем, поэтому наборы сравнимы между
 * собой; замер по пальцу плясал от прогона к прогону вдвое):
 *
 *   было (0.80 / 0.38 c / −320)   пик 111.5 px за кадр, покой 1085 мс
 *   первая попытка (0.92 / 0.54)  пик  61.5,            покой  958 мс
 *   1.00 / 0.46 c, импульс 0.55   пик  74.7,            покой 1007 мс
 *   ВЗЯТО: 1.00 / 0.52 c, 0.45    пик  23.6,            покой  765 мс
 *   1.00 / 0.58 c, импульс 0.35   пик  54.0,            покой 1039 мс
 *
 * Взятый набор спокойнее исходного почти впятеро по пиковой скорости и при
 * этом успокаивается БЫСТРЕЕ — то есть «плавно» здесь не значит «медленно».
 *
 * ИТОГО ИЗМЕНЕНО:
 *   · бросок — damping 0.80 → 1.00 (овершут снят, он и читался щелчком),
 *     response 0.38 → 0.52 c, а скорость пальца впускается наполовину
 *     (`vel * 0.45`): именно она разгоняла кадр до ста пикселей за кадр;
 *   · возврат домой 0.40 → 0.52 c: если жест не дотянул до порога, карточка
 *     возвращается так же мягко, как уходит;
 *   · возврат улетевшего под низ стопки 0.52 → 0.66 c;
 *   · кнопка и клавиатура получили те же числа, что жест.
 *
 * ЧЕГО НЕ ТРОНУТО НАРОЧНО: слежение за пальцем остаётся 1:1 (карточка обязана
 * стоять под пальцем, а не догонять его), порог переворота — те же 34 %,
 * проекция импульса и резина по вертикали прежние. Мягче сделан отпуск, а не
 * сам жест: замедлять слежение значило бы сделать стопку вязкой, а не плавной.
 *
 * ═══ СТОРОНЫ РАЗВЁРНУТЫ (Ф63) ═══════════════════════════════════════════
 * Владелица: «листание влево пусть будет вперед, а листание вправо будет
 * назад». Это прямая отмена Ф62, где было наоборот, — и отменяется только
 * СТОРОНА. Всё, что Ф62 вывела про механику, остаётся в силе слово в слово,
 * потому что выводы были не про «влево» и «вправо», а про их СВЯЗЬ:
 *  · назад кадр приходит с той стороны, куда уходит вперёд, — иначе он
 *    телепортируется. Вперёд теперь влево, значит предыдущий возвращается
 *    из-за ЛЕВОГО края и едет вправо, вслед за пальцем;
 *  · смена верхнего у «назад» происходит сразу, у броска вперёд — по порогу
 *    62 % ширины (причины — у самих ветвей ниже);
 *  · кнопка и клавиатура показывают ровно то же движение, что жест.
 * Ни одно число физики здесь не изменилось: перевернулись знаки.
 *
 * ═══ «НАЗАД» ПЕРЕПИСАН (Ф64) ════════════════════════════════════════════
 * «Пользователю кажется, что это глюк». Числа пружин снова не тронуты —
 * изменилось, ЧТО именно движется: вправо стопка теперь почти не поддаётся
 * (резина), а по отпускании играет обратная анимация «вперёд». Полный разбор,
 * что читалось сбоем и почему, — в шапке `stepBack` ниже.
 *
 * ═══ «ВПЕРЁД» ПОДТЯНУТ К «НАЗАД» (Ф65) ══════════════════════════════════
 * «Сделай перелистывание стопки вперед такой же мягкой, как назад». Числа
 * пружин снова НЕ тронуты, и это третья правка подряд, где смягчение вышло не
 * из вязкости: уходящий кадр теперь тает тем же коридором, каким проявляется
 * возвращаемый, и целится не за полторы ширины, а за одну. Разбор и замеры —
 * у констант `VEIL_NEAR`/`VEIL_FAR`/`THROW_TO` ниже.
 *
 * Остальное в физике без изменений:
 *  · X и Y — независимые пружины;
 *  · перехват в любой момент: новый захват читает текущее положение,
 *    скорость не обрывается, направление можно развернуть на полпути.
 */

export type RackApi = {
  /** индекс кадра, лежащего сверху */
  top: number;
  /** мышь/палец держит стопку прямо сейчас */
  held: boolean;
  /** ref на контейнер стопки */
  ref: RefObject<HTMLDivElement | null>;
  /** тот же переворот без жеста: кнопка и клавиатура. В B это был `bring(i)` —
   *  «положить наверх кадр номер i», и он имел смысл при стопке из двух. В пуле
   *  из восьми прыжок через полстопки одним движением означал бы, что механика
   *  перелистывания у мыши и у клавиатуры разная. Переворот один: следующий. */
  advance: () => void;
  /** «назад» без жеста — клавиатура. Появился на Ф63 вместе с разворотом
   *  сторон: с Ф62 у жеста есть оба направления, а у клавиатуры был только
   *  один, и стрелка «не туда» просто молчала. Теперь у обоих вводов один
   *  словарь: вперёд и назад. */
  retreat: () => void;
  /** движение выключено пользователем — рисуем стопку как список кадров */
  still: boolean;
};

type Layer = { x: number; y: number; vx: number; vy: number; damp: number; resp: number; tx: number };

const PEEK_X = 13; // px, насколько следующий кадр выглядывает вправо
const PEEK_Y = 13; // px, и вниз
const BACK_S = 0.962; // масштаб каждого следующего уровня вглубь
const DEPTH_MAX = 3; // сколько кадров стопки видно; глубже они закрыты полностью
/** Доворот по глубине, градусы на уровень. Числа неравные и детерминированы
 *  индексом кадра: ровная стопка выглядит как стопка карточек, неровная — как
 *  пачка отпечатков. */
const TILT = [-1.4, 0.9, -0.6, 1.6, -1.1, 0.5, 1.2, -0.8];
const DECEL = 0.996;
const THRESH = 0.34; // доля ширины карточки
/* ═══ ОДИН КОРИДОР УХОДА И ПРИХОДА (Ф65) ═════════════════════════════════
   Владелица: «сделай перелистывание стопки вперед такой же мягкой, как назад».

   ЗАМЕР ПОКАЗАЛ ДВЕ РАЗНИЦЫ, обе числовые, а не «на ощупь»:
    1. назад кадр ПРОЯВЛЯЛСЯ (0.12 → 1), вперёд — ПРОПАДАЛ разом: на 62 %
       ширины он переставал быть верхним и получал прозрачность 0 от глубины.
       Пропажа целой фотографии за один кадр и есть та жёсткость;
    2. пик хода 68 px за кадр против 46 у возврата — ровно в полтора раза, и
       ровно во столько же различался путь: вперёд кадр летел на 1,5 ширины,
       назад приезжал с одной.

   ОТСЮДА ОБЩИЕ ЧИСЛА. `VEIL_NEAR`…`VEIL_FAR` — коридор, в котором кадр тает,
   и он один на оба направления: уходящий в нём растворяется, возвращаемый в
   нём же проявляется. `VEIL_FAR` — это одновременно точка, где уходящий
   перестаёт быть верхним (он там уже невидим), и точка, откуда стартует
   возвращаемый. То есть у обеих анимаций буквально одни и те же границы, а
   не два похожих числа, которые разъедутся при следующей правке.

   ЧТО ПОЛУЧИЛОСЬ, замером на детерминированном вводе (кнопка и клавиша, как
   в Ф61 — палец пляшет от прогона к прогону вдвое):

     наибольший скачок прозрачности за кадр   было 1.00 → стало 0.31
     пик хода «вперёд» против «назад»         было 68/46 → стало 46/39 (1.18×)
     нажатие → смена счётчика                 300–390 мс, ровно

   ПОЧЕМУ НЕ ДОВЁЛ ДО ЕДИНИЦЫ. Ровное равенство пиков достигается только
   `THROW_TO = VEIL_FAR`, и тогда кадр подползает к границе асимптотически:
   переворот откладывается на секунду с лишним, счётчик отстаёт от картинки, а
   на следующий бросок стопка не отвечает вовсе (`flying` ещё занят). Поймано
   прогоном — первая попытка была именно такой. Разница в 1,18 раза глазом не
   читается, застрявший счётчик читается сразу. */
const VEIL_NEAR = 0.55; // ближе этой доли ширины кадр полностью непрозрачен
const VEIL_FAR = 0.85; // дальше — полностью прозрачен: ушёл за край стопки
/** Куда целится брошенный вперёд кадр — чуть дальше `VEIL_FAR`, см. абзац
 *  «почему не довёл до единицы» выше. Было 1.5 (Ф61): именно оттуда брались
 *  лишние полтора раза скорости, потому что пик пропорционален пути. */
const THROW_TO = 1.0;

/** Проекция импульса по Apple (Designing Fluid Interfaces), px */
const project = (v: number) => (v / 1000) * DECEL / (1 - DECEL);

/** Резиновое сопротивление за границей */
const rubber = (over: number, dim: number, c = 0.55) =>
  (over * dim * c) / (dim + c * Math.abs(over));

/** Прозрачность кадра В ПУТИ — одна функция на оба направления (Ф64 завела
 *  её для въезда, Ф65 отдала ей и уход). Дома кадр непрозрачен, за
 *  `VEIL_FAR` его нет вовсе, между — линейно. Уходящий проходит коридор от
 *  единицы к нулю, возвращаемый — от нуля к единице, и это буквально одно
 *  движение, прочитанное в две стороны. */
const veil = (x: number, W: number) =>
  Math.min(1, Math.max(0, (W * VEIL_FAR - Math.abs(x)) / (W * (VEIL_FAR - VEIL_NEAR))));

/* Крючок для съёмки доказательств: ?rack=-96 держит верхний кадр вытянутым на
   96 px влево, чтобы кадр поймал механику в середине жеста — headless-браузер
   палец не приставляет. На продукт не влияет, в продуктовом пути параметра нет. */
const DEMO_X = (() => {
  if (typeof location === 'undefined') return null;
  const v = new URLSearchParams(location.search).get('rack');
  const n = v === null ? NaN : Number(v);
  return Number.isFinite(n) ? n : null;
})();

export function useRack(count = 2): RackApi {
  const ref = useRef<HTMLDivElement>(null);
  const [top, setTop] = useState(0);
  const [held, setHeld] = useState(false);
  const [still, setStill] = useState(false);

  const L = useRef<Layer[]>(
    Array.from({ length: count }, () => ({ x: 0, y: 0, vx: 0, vy: 0, damp: 1, resp: 0.4, tx: 0 })),
  );
  const topRef = useRef(0);
  /** `raw` — положение верхнего кадра, каким оно было бы БЕЗ сопротивления
   *  вправо (Ф64). Порог жеста «назад» считается по пальцу, а не по тому,
   *  насколько поддалась стопка: она нарочно почти не поддаётся. */
  const drag = useRef<{ id: number; sx: number; sy: number; ox: number; oy: number; raw: number } | null>(
    null,
  );
  const flying = useRef<number | null>(null);
  /** Кадр, который прямо сейчас ВЪЕЗЖАЕТ обратно (жест/кнопка «назад», Ф64).
   *  Нужен только для проявления: см. `enterFade` и `paint`. */
  const entering = useRef<number | null>(null);

  /* ——— применение состояния к DOM: один раз за кадр, без ре-рендера React ———
     Правка гибрида (лок, Ф19): в B стопка была из двух кадров, и «не верхний»
     означало ровно один нижний. В пуле из восьми это перестало работать: все
     семь получали один и тот же выступ и ложились в идеальный штабель, то есть
     стопка снова читалась как два кадра. Теперь у каждого слоя есть ГЛУБИНА —
     порядковый номер от верхнего, — и выступ, масштаб и доворот считаются от
     неё. Видимых уровней три: глубже кадр всё равно закрыт соседями, а держать
     восемь живых теней в композите незачем.

     Доворот на глубину — не украшение: это отпечатки, лежащие в руке, а не
     карточки интерфейса. Углы детерминированы индексом, поэтому стопка при
     каждой загрузке одна и та же и её можно снимать. */
  const paint = useCallback(() => {
    const el = ref.current;
    if (!el) return;
    const W = el.clientWidth || 1;
    const t = topRef.current;
    const k = Math.min(1, Math.abs(L.current[t].x) / (W * THRESH));
    for (let i = 0; i < count; i++) {
      const node = el.querySelector<HTMLElement>(`[data-layer="${i}"]`);
      if (!node) continue;
      const l = L.current[i];
      if (i === t) {
        node.style.zIndex = String(count + 1);
        /* Верхний кадр не полностью непрозрачен ровно в двух случаях, и это
           один и тот же случай, прочитанный в две стороны: он въезжает домой
           (Ф64) или улетает вперёд (Ф65). В покое `entering`/`flying` пусты,
           и никакой прозрачности не считается. */
        node.style.opacity =
          i === entering.current || i === flying.current ? veil(l.x, W).toFixed(3) : '1';
        node.style.transform =
          `translate3d(${l.x.toFixed(2)}px,${l.y.toFixed(2)}px,0) rotate(${(l.x / 34).toFixed(3)}deg)`;
      } else {
        const depth = (i - t + count) % count; // 1 — сразу под верхним
        const d = Math.min(depth, DEPTH_MAX);
        node.style.zIndex = String(count - depth);
        // за третьим уровнем кадр не рисуем вовсе: он полностью закрыт
        node.style.opacity = depth > DEPTH_MAX ? '0' : '1';
        // подсказка в сторону жеста: следующий кадр подтягивается к месту
        const lift = depth === 1 ? k : 0;
        const s = Math.pow(BACK_S, d) + (1 - BACK_S) * lift;
        const px = PEEK_X * (d - lift) + l.x;
        const py = PEEK_Y * (d - lift) + l.y;
        const tilt = TILT[i % TILT.length] * d;
        node.style.transform =
          `translate3d(${px.toFixed(2)}px,${py.toFixed(2)}px,0) rotate(${tilt.toFixed(2)}deg) scale(${s.toFixed(4)})`;
      }
    }
  }, [count]);

  /* ——— пружинный цикл ——— */
  useEffect(() => {
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
      setStill(true);
      return;
    }
    if (DEMO_X !== null) {
      L.current[0].x = DEMO_X;
      L.current[0].y = DEMO_X * 0.06;
      setHeld(true);
      paint();
      return;
    }
    paint();

    /* ═══ ПОКОЙ (Ф43) — «сайт ещё виснет» ════════════════════════════════
       Стопка стоит неподвижно почти всё время: пружины работают только пока
       её тянут пальцем и пока улетевший кадр возвращается под низ. Прежний
       цикл всё равно считал двенадцать пружин и перерисовывал стопку
       шестьдесят раз в секунду — на первом экране, то есть ровно там, где
       читатель проводит больше всего времени.

       Теперь кадр пропускается, если стопку никто не держит, ничего не
       летит и все смещения со скоростями улеглись ниже 0,05 px. Порог тот
       же, что у звёзд, и по той же причине: `paint` округляет координаты, и
       движение мельче порога до экрана не доезжает.

       Физика не тронута ни одним числом — изменилось только то, считается
       ли она, когда считать нечего. */
    const STILL = 0.05;

    const loop = (_now: number, dt: number) => {
      const el = ref.current;
      const W = el?.clientWidth || 1;

      let moving = !!drag.current || flying.current !== null;

      for (let i = 0; i < count; i++) {
        const l = L.current[i];
        if (drag.current && i === topRef.current) continue; // палец держит — пружина молчит
        const w = (Math.PI * 2) / l.resp;
        l.vx += (w * w * (l.tx - l.x) - 2 * w * l.damp * l.vx) * dt;
        l.vy += (w * w * (0 - l.y) - 2 * w * l.damp * l.vy) * dt;
        l.x += l.vx * dt;
        l.y += l.vy * dt;

        // въехавший обратно кадр проявился целиком — метка больше не нужна,
        // иначе следующий жест по нему считался бы въездом (Ф64)
        if (entering.current === i && Math.abs(l.x) <= W * VEIL_NEAR) entering.current = null;

        /* Переворот совершается, когда улетающий кадр вышел за коридор: там
           он уже полностью прозрачен (Ф65), то есть его пропажа из верхних
           не видна вовсе. До Ф65 граница стояла на `VEIL_NEAR`, где кадр был
           ещё непрозрачен и исчезал рывком — это и была жёсткость «вперёд». */
        if (flying.current === i && Math.abs(l.x) > W * VEIL_FAR) {
          flying.current = null;
          const next = (i + 1) % count;
          topRef.current = next;
          setTop(next);
          L.current[next].x = 0;
          L.current[next].y = 0;
          L.current[next].vx = 0;
          L.current[next].vy = 0;
          L.current[next].tx = 0;
          // улетевший теперь нижний: возвращается из-за края под стопку
          l.tx = 0;
          l.damp = 1;
          l.resp = 0.66; // Ф61: было 0.52
        }

        if (!moving) {
          moving =
            Math.abs(l.x - l.tx) > STILL ||
            Math.abs(l.y) > STILL ||
            Math.abs(l.vx) > STILL ||
            Math.abs(l.vy) > STILL;
        }
      }
      if (moving) paint();
    };
    return onFrame(loop);
  }, [count, paint]);

  /* ——— «НАЗАД»: один код на жест вправо, кнопку и клавиатуру ———
     Ф63 вынесла эту ветвь в отдельную функцию по той же причине, по которой
     Ф61 свела числа кнопки и жеста: переворот, вызываемый несколькими
     вводами, обязан быть ОДНИМ переворотом, а не похожими кусками кода,
     которые разъедутся на следующей правке. Сосед `advance` — та же роль для
     «вперёд».

     ═══ ПЕРЕПИСАНО Ф64 — «пользователю кажется, что это глюк» ══════════════
     Владелица: «при пролистывании стопки анимация назад должна быть чуть
     другой. возможно, сделай анимацию вперед в обратном порядке».

     ЧТО ИМЕННО ЧИТАЛОСЬ ГЛЮКОМ, найдено разбором редакции Ф63, а не на
     ощупь. Там палец тянул ВЕРХНИЙ кадр вправо 1:1, и при отпускании
     происходили два движения сразу и НАВСТРЕЧУ друг другу:
       · верхний кадр отскакивал домой, то есть ВЛЕВО, против пальца, —
         а отскок под палец в любом интерфейсе означает «жест отменён»;
       · одновременно справа налево... нет, слева направо въезжал предыдущий.
     Читатель получал два противоположных сообщения в один момент: «твой жест
     не засчитан» и «вот тебе новый кадр». Отсюда и ощущение сбоя, хотя
     механика работала ровно так, как задумано.

     ЧТО СТАЛО. Кадр, который надо вернуть, — не тот, что под пальцем. Значит
     под пальцем и не должно ничего ехать: вправо стопка теперь почти не
     поддаётся (резина в `onMove`, ход около двадцати пикселей на полтораста
     пальца) — этого хватает, чтобы стопка ответила на прикосновение, и мало,
     чтобы отскок прочитался отменой. А по отпускании играет ровно ОБРАТНАЯ
     анимация «вперёд»: предыдущий кадр приезжает слева в дом теми же числами
     пружины, какими уходящий уезжает из дома влево.

     ГРАНИЦА У ОБОИХ НАПРАВЛЕНИЙ ОДНА (`FLIP`, 62 % ширины): вперёд кадр в
     ней пропадает, назад — в ней уже полностью проявился (`enterFade`).
     Поэтому ни один не возникает и не исчезает рывком посреди пустоты, а
     видимые куски двух анимаций зеркальны.

     ЦЕНА, названная честно: жест «назад» перестал быть перетаскиванием и
     стал броском — довести кадр пальцем до половины и передумать больше
     нельзя. Иначе пришлось бы переносить палец на въезжающий кадр (то есть
     менять верхний прямо посреди жеста), а это куда больше поводов для
     нового «глюка», чем стоит возможность скрабить возврат.

     СМЕНА ВЕРХНЕГО ПРОИСХОДИТ СРАЗУ, а не по достижении порога, как у броска
     вперёд. У броска смена отложена: пока улетающий кадр не ушёл за границу,
     он ещё виден и обязан оставаться верхним. Здесь наоборот —
     возвращающийся кадр обязан быть верхним с первого же пикселя, иначе он
     въезжал бы ПОД стопкой.

     ТЕКУЩИЙ ВЕРХНИЙ НЕ ДВИГАЕТСЯ ВОВСЕ. Ему ставится дом и обнуляется
     скорость: его не бросали, его накрывают. А то, что он при этом не
     прыгает в положение второго слоя, даёт уже существующий `lift` в
     `paint` — пока въезжающий кадр далеко, подъём равен единице, и накрытый
     кадр стоит ровно там, где стоял, съезжая под стопку по мере приезда
     соседа. Тот же механизм, что подтягивает второй кадр при броске вперёд,
     только прочитанный в обратную сторону. */
  const stepBack = useCallback(() => {
    const t = topRef.current;
    const prev = (t - 1 + count) % count;
    if (still) {
      topRef.current = prev;
      setTop(prev);
      return;
    }
    // тот же запрет, что у `advance`: пока кадр летит, второй переворот его
    // собьёт — верхним окажется тот, кто уже ушёл за край
    if (flying.current !== null) return;
    const W = ref.current?.clientWidth || 300;
    const out = L.current[t];
    /* Положение НЕ обнуляется, обнуляется только цель: на жесте кадр отошёл
       на резине пикселей на двадцать, и мгновенный возврат этих двадцати —
       заметный дёрг целой фотографии за один кадр. Пружина снимает их
       незаметно. Замерено: 23 px при пальце в 150. */
    out.tx = 0;
    out.vx = 0;
    out.vy = 0;
    out.damp = 1;
    out.resp = 0.52;
    const p = L.current[prev];
    p.x = -W * VEIL_FAR;
    p.y = 0;
    // тот же толчок по модулю, что у `advance`, только в свою сторону
    p.vx = 144;
    p.vy = 0;
    p.tx = 0;
    p.damp = 1;
    p.resp = 0.52;
    entering.current = prev;
    topRef.current = prev;
    setTop(prev);
  }, [count, still]);

  /* ——— ввод: один код на мышь, палец и стилус ——— */
  useEffect(() => {
    const el = ref.current;
    if (!el || still) return;

    const onDown = (e: PointerEvent) => {
      if (e.button !== undefined && e.button !== 0) return;
      const t = topRef.current;
      const l = L.current[t];
      // перехват на лету: отсчёт от текущего экранного положения,
      // скорость не обнуляется — разворот на полпути не даёт «кирпичной стены»
      drag.current = { id: e.pointerId, sx: e.clientX, sy: e.clientY, ox: l.x, oy: l.y, raw: l.x };
      flying.current = null;
      /* Кадр перехвачен посреди въезда — проявление отменяется, дальше он
         обычный верхний кадр под пальцем и обязан быть непрозрачным (Ф64). */
      entering.current = null;
      el.setPointerCapture(e.pointerId);
      setHeld(true);
    };

    let lastT = 0;
    let lastX = 0;
    let vel = 0;
    const onMove = (e: PointerEvent) => {
      const d = drag.current;
      if (!d || d.id !== e.pointerId) return;
      const l = L.current[topRef.current];
      const H = el.clientHeight || 1;
      const W = el.clientWidth || 1;
      d.raw = d.ox + (e.clientX - d.sx);
      /* ВЛЕВО — 1:1, как было: там палец несёт именно этот кадр, и он обязан
         стоять под пальцем, а не догонять его.
         ВПРАВО — резина (Ф64). Вправо уезжать нечему: «назад» возвращает
         ДРУГОЙ кадр, слева, а этот остаётся на месте и будет накрыт. Раньше
         он ехал за пальцем 1:1 и при отпускании отскакивал обратно — то есть
         говорил «жест отменён» ровно в тот момент, когда рядом въезжал
         возвращённый кадр. Два противоположных сообщения разом и читались
         глюком; разбор целиком — в шапке `stepBack`.
         Коэффициент 0.18 вместо обычных 0.55: сто пятьдесят пикселей пальца
         дают около двадцати трёх ходу — стопка заметно отвечает на
         прикосновение и заметно не едет. */
      l.x = d.raw > 0 ? rubber(d.raw, W, 0.18) : d.raw;
      const rawY = d.oy + (e.clientY - d.sy) * 0.35;
      l.y = Math.abs(rawY) > 60 ? Math.sign(rawY) * (60 + rubber(Math.abs(rawY) - 60, H)) : rawY;
      const now = performance.now();
      if (now > lastT) {
        const inst = ((e.clientX - lastX) / (now - lastT)) * 1000;
        vel = vel * 0.6 + inst * 0.4; // сглаженная скорость пальца, px/s
      }
      lastT = now;
      lastX = e.clientX;
      paint();
    };

    const onUp = (e: PointerEvent) => {
      const d = drag.current;
      if (!d || d.id !== e.pointerId) return;
      drag.current = null;
      setHeld(false);
      const t = topRef.current;
      const l = L.current[t];
      const W = el.clientWidth || 1;
      /* Скорость пальца влипает в кадр, только если палец нёс ЕГО, то есть
         тянул влево (Ф64). На жесте вправо кадр стоял на резине и никуда не
         летит: влитая скорость раскачала бы его вправо-влево ровно под
         въезжающим соседом. Ф61: и в оставшемся случае она гасится вдвое. */
      l.vx = d.raw > 0 ? 0 : vel * 0.45;
      l.vy = 0;
      const projected = l.x + project(vel);
      /* Порог «назад» считается по ПАЛЬЦУ (`d.raw`), а не по кадру: кадр
         вправо почти не едет нарочно, и мерить порог по нему значило бы
         требовать жест впятеро длиннее. */
      const projectedRaw = d.raw + project(vel);
      if (projected < -W * THRESH) {
        /* ВЛЕВО — ВПЕРЁД (Ф63, «листание влево пусть будет вперед»). Кадр
           уходит туда, куда шёл палец, и следующий становится верхним. */
        l.tx = -W * THROW_TO;
        l.damp = 1; // Ф61: было 0.8 — овершут в конце читался щелчком
        l.resp = 0.52; // Ф61: было 0.38
        flying.current = t;
      } else if (projectedRaw > W * THRESH) {
        /* ВПРАВО — НАЗАД (Ф63, «листание вправо будет назад»). Механика — в
           `stepBack` выше, общая с кнопкой и клавиатурой; там же разбор, что
           именно правит Ф64 и почему. */
        stepBack();
      } else {
        l.tx = 0;
        l.damp = 1;
        l.resp = 0.52; // Ф61: было 0.4
      }
      vel = 0;
    };

    el.addEventListener('pointerdown', onDown);
    el.addEventListener('pointermove', onMove);
    el.addEventListener('pointerup', onUp);
    el.addEventListener('pointercancel', onUp);
    return () => {
      el.removeEventListener('pointerdown', onDown);
      el.removeEventListener('pointermove', onMove);
      el.removeEventListener('pointerup', onUp);
      el.removeEventListener('pointercancel', onUp);
    };
  }, [paint, still, stepBack]);

  /* ——— тот же переворот без жеста: кнопка и клавиатура ——— */
  const advance = useCallback(() => {
    const t = topRef.current;
    if (still) {
      const n = (t + 1) % count;
      topRef.current = n;
      setTop(n);
      return;
    }
    if (flying.current !== null) return; // кадр уже в полёте, второй бросок его собьёт
    const el = ref.current;
    const W = el?.clientWidth || 300;
    const l = L.current[t];
    /* Кадр бросают вперёд, не дождавшись конца въезда: проявление отменяется,
       иначе он таял бы по дороге ВПЕРЁД, а таять положено только на въезде. */
    entering.current = null;
    /* НАПРАВЛЕНИЕ РАЗВЁРНУТО Ф63: влево, а не вправо (Ф62 держала здесь
       правое, потому что тогда вперёд было вправо). Стороны заняты смыслом,
       и кнопка «следующий кадр» обязана показывать то же движение, что жест
       вперёд, — иначе один и тот же переворот выглядел бы зеркально в
       зависимости от того, чем вызван. Знак скорости перевёрнут вместе с
       целью: положительная скорость влево — это толчок против собственного
       хода, и первый кадр броска дёрнулся бы не в ту сторону. */
    l.tx = -W * THROW_TO;
    /* Ф61: те же числа, что у броска пальцем, — кнопка и клавиатура обязаны
       двигать стопку ровно так же, как жест. */
    l.damp = 1;
    l.resp = 0.52;
    l.vx = -144;
    flying.current = t;
  }, [count, still]);

  return { top, held, ref, advance, retreat: stepBack, still };
}
