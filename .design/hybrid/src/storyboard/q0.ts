export interface Tile {
  value: string;
  label: string;
}

/** Тайл Q0. `тег` — тег архива, без которого тайл не показывается. */
export interface Q0Tile extends Tile {
  тег?: string;
}

export const Q0_TITLE = 'Какой у вас повод посниматься?';

/** Порядок — дерева Ф33, менять его нельзя без владелицы.
 *  «Скоро день рождения» показывается, только если в архиве реально есть
 *  кадры с этим поводом: если тег когда-нибудь пропадёт, тайл исчезнет сам,
 *  без правки кода. Два других тайла от данных не зависят — они задают
 *  ФОРМАТ, а форматы в архиве есть всегда (`STORYBOARD.md` § 5). */
export const Q0_TILES: Q0Tile[] = [
  { value: 'день рождения', label: 'Скоро день рождения', тег: 'день рождения' },
  { value: 'вайб', label: 'Вайб имеется' },
  { value: 'любовь', label: 'Запечатлеть любовь' },
];

/** Имя параметра ссылки «на страницу с уже отмеченным ответом». */
export const POVOD_PARAM = 'povod';

/**
 * Значения ответа ↔ короткие слаги для адресной строки.
 *
 * ПОЧЕМУ НЕ САМО ЗНАЧЕНИЕ. Значения дерева — кириллица («день рождения»), и
 * в адресе она превращается в `%D0%B4%D0%B5%D0%BD%D1%8C…`. Такую ссылку
 * человек не прочитает и не перешлёт; `/storyboard.html?povod=den-rozhdeniya`
 * прочитает.
 *
 * Слаг — ЧАСТЬ АДРЕСА, а не внутреннее значение: менять его после публикации
 * значит ломать уже отправленные кому-то ссылки. Значения дерева при этом
 * менять можно свободно — они внутренние, за них отвечает эта таблица.
 */
export const POVOD_SLUG: Record<string, string> = {
  'день рождения': 'den-rozhdeniya',
  вайб: 'vaib',
  любовь: 'lyubov',
};

/** Слаг → значение ответа. `null`, если слага нет в таблице — тогда адрес
 *  просто игнорируется и читатель видит обычный вход, а не пустой результат. */
export function povodFromSlug(slug: string | null): string | null {
  if (!slug) return null;
  const found = Object.entries(POVOD_SLUG).find(([, s]) => s === slug);
  return found ? found[0] : null;
}
