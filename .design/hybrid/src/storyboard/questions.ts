/**
 * ДЕРЕВО ВОПРОСОВ — РЕДАКЦИЯ 4 (Ф33, `STORYBOARD.md` § 13). Заменяет плоский
 * `buildQuestions()` редакций 1–3: раньше все вопросы задавались в одном
 * фиксированном порядке для всех, теперь порядок и состав вопросов зависят от
 * ответа на предыдущий — настоящее дерево, источник истины — `FACTS.md` Ф33
 * (дословное дерево цитатами владелицы), билдер не упрощал ветвление.
 *
 * Экранный текст здесь — АВТОРСКИЙ ТЕКСТ БИЛДЕРА там, где дерево не даёт
 * формулировки дословно (подписи мест/материала унифицированы между ветками,
 * т.к. в дереве владелицы они почти дословно совпадают между ветками с
 * минимальными вариациями — «вы» то есть, то нет). Заголовки вопросов и их
 * ответы, которые дерево ЗАДАЁТ дословно, воспроизведены буква в букву.
 *
 * ═══ СТРУКТУРА ДЕРЕВА (FACTS.md Ф33, п.4) ═══
 *
 *   Q0 «Какой у вас повод посниматься?»
 *   ├── «Скоро день рождения»                                (id: повод = 'день рождения')
 *   ├── «Вайб имеется»                                        (id: повод = 'вайб')
 *   │     Q1 «Хотели бы посниматься в одиночку или вдвоём?»   (id: формат)
 *   │     ├── «В одиночку» (формат=индивидуальная)
 *   │     │     Q2 «Вы — парень или девушка?»                 (id: пол)
 *   │     └── «Вдвоём» (формат=парная)
 *   │     (третий тайл «Творческая — на моё усмотрение» СНЯТ Ф39 п.11 —
 *   │      см. комментарий у `Q_VIBE_FORMAT` и цену этой правки там же)
 *   └── «Запечатлеть любовь»                                  (id: повод = 'любовь',
 *         формат жёстко «парная» без отдельного вопроса — решение координатора,
 *         FACTS.md Ф33: «любовь между двумя — самое естественное прочтение»)
 *
 *   Дальше ОДИНАКОВО для всех веток (в том числе «день рождения» — дерево
 *   владелицы явно просит эти вопросы и там, см. `pick.ts` про честность):
 *     Q «Хотели бы на плёнку/цифру или всё сразу?»    (id: материал)
 *     Q «Где вы хотели бы провести съёмку?»           (id: место)
 *     Q «Уже есть готовый образ?»                      (id: образ) → РЕЗУЛЬТАТ
 *
 * `nextQuestionInTree()` — единственная функция, которая знает эту структуру:
 * принимает УЖЕ ДАННЫЕ ответы (словарь id→value) и возвращает СЛЕДУЮЩИЙ вопрос
 * или `null`, если дерево пройдено и пора считать результат. Экран (`Storyboard
 * App.tsx`) не хранит номер шага — только историю пар {вопрос, ответ}, и на
 * каждом шаге спрашивает эту функцию, что показать дальше. Это и даёт лестницу
 * «предыдущие вопросы видны с ответом» естественно: история просто растёт.
 */

/* `Tile` переехал в `q0.ts` (Ф63) и ре-экспортируется отсюда: снаружи этот
   файл остаётся тем же адресом за типами дерева, менять чужие импорты
   из-за переезда объявления не за чем. */
export type { Tile };

export interface QuestionDef {
  id: string;
  title: string;
  hint?: string;
  tiles: Tile[];
}

