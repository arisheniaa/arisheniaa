import type { StoryboardPhoto } from './types';
import { normalizeOccasionTags } from './pick';
import { OCCASION_NONE, SKIP_LOOK } from './types';

/**
 * ПЯТЬ ОСЕЙ БРИФА (`BRIEF-STORYBOARD.md` § 3): повод / формат / материал /
 * место / образ («повод» — было «настроение», сужено и вынесено ПЕРВЫМ
 * вопросом, см. комментарий ниже и `pick.ts`). Экранный текст здесь —
 * АВТОРСКИЙ ТЕКСТ БИЛДЕРА, не из `COPY.md`:
 * для этой фичи зон в `COPY.md` не существует вовсе (это новая фича, не
 * поле существующей редакции). Тон держится в рамках голоса сайта (`FACTS.md`
 * Ф11 — тепло, обращение к человеку), без слов из чёрного списка COPY
 * («атмосфера», «искренний», «живой», восклицательные знаки).
 *
 * Тайлы, а не текстовый ввод (§ 7 брифа — прямое требование, не предложение
 * исполнителя: «кнопки-плитки (не текстовый ввод)»).
 */

export type QuestionId = 'формат' | 'материал' | 'место' | 'образ' | 'повод';

export interface Tile {
  value: string;
  label: string;
}

export interface QuestionDef {
  id: QuestionId;
  title: string;
  hint?: string;
  tiles: Tile[];
}

function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/**
 * Строит вопросы ПО ДАННЫМ, а не по хардкоду тегов: список «образ» и наличие
 * вопроса «повод» читаются из реального манифеста. Если архив изменится
 * (появятся другие поводы, другие образы), вопросы обновятся сами, без
 * правки этого файла — ровно то, что требует `FACTS.md` Ф30 про ось
 * «настроение»: «если позже придут другие категории повода — экран
 * расширяется без изменения механики».
 */
export function buildQuestions(photos: StoryboardPhoto[]): QuestionDef[] {
  const lookTags = Array.from(new Set(photos.flatMap((p) => p.образ))).sort((a, b) =>
    a.localeCompare(b, 'ru'),
  );

  const occasionTags = Array.from(
    new Set(photos.flatMap((p) => normalizeOccasionTags(p.настроение))),
  );

  const questions: QuestionDef[] = [];

  /* «Повод» — ПЕРВЫМ вопросом, не последним. Находка при самопроверке
     (`pick.ts`, комментарий вверху файла): все фото с реальным поводом не
     несут формата вовсе, и подбор по поводу идёт в ОБХОД дальнейших вопросов
     («кто в кадре», «где») — эти теги у мини-сета повода просто отсутствуют.
     Если задать повод последним, читатель отвечает на четыре вопроса, три из
     которых заведомо не повлияют на результат при выборе реального повода —
     это трата его времени на вопросы, ответы на которые будут отброшены.
     Первым вопросом и с быстрым переходом сразу к результату
     (`StoryboardApp.tsx`, `choose()`) это честнее и короче.
     Экран показывается, только если в архиве вообще есть хоть один повод —
     если тег когда-нибудь пропадёт из архива, экран исчезнет сам. */
  if (occasionTags.length > 0) {
    questions.push({
      id: 'повод',
      title: 'Есть повод?',
      hint: 'Если да — покажу кадры именно с этим поводом, и на этом раскадровка готова.',
      tiles: [
        ...occasionTags.map((tag) => ({ value: tag, label: capitalize(tag) })),
        { value: OCCASION_NONE, label: 'Без повода — обычная съёмка' },
      ],
    });
  }

  questions.push(
    {
      id: 'формат',
      title: 'Кто будет в кадре?',
      tiles: [
        { value: 'индивидуальная', label: 'Один человек' },
        { value: 'парная', label: 'Двое' },
        { value: 'творческая', label: 'Творческая — на моё усмотрение' },
      ],
    },
    {
      id: 'материал',
      title: 'Цифра или плёнка?',
      tiles: [
        { value: 'цифра', label: 'Цифра' },
        { value: 'пленка', label: 'Плёнка' },
        { value: 'любой', label: 'Не важно — покажи оба' },
      ],
    },
    {
      id: 'место',
      title: 'Где снимаем?',
      hint: 'Если ещё не решили — не страшно, место можно выбрать позже вместе.',
      tiles: [
        { value: 'природа', label: 'Природа' },
        { value: 'город', label: 'Город' },
        { value: 'студия', label: 'Студия' },
        { value: 'неважно', label: 'Пока не знаю' },
      ],
    },
    {
      id: 'образ',
      title: 'Какой образ ближе?',
      hint: 'Собрано из моих реальных съёмок. Не откликнулось — придумаем образ вместе, когда напишете.',
      tiles: [
        ...lookTags.map((tag) => ({ value: tag, label: capitalize(tag) })),
        { value: SKIP_LOOK, label: 'Неважно — придумаем вместе' },
      ],
    },
  );

  return questions;
}
