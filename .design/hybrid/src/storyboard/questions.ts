const Q_GENDER: QuestionDef = {
  id: 'пол',
  title: 'Вы — парень или девушка?',
  tiles: [
    { value: 'парень', label: 'Парень' },
    { value: 'девушка', label: 'Девушка' },
  ],
};

/* Значения тайлов — сразу значения `FormatBucket`, чтобы не заводить отдельный
   маппинг «ответ дерева» → «формат архива»: одна и та же строка используется
   и как ключ ветвления, и как `answers.формат` для `pick.ts`. */
const Q_VIBE_FORMAT: QuestionDef = {
  id: 'формат',
  title: 'Хотели бы посниматься в одиночку или вдвоём?',
  tiles: [
    { value: 'индивидуальная', label: 'В одиночку' },
    { value: 'парная', label: 'Вдвоём' },
    // ДОБАВКА координатора, не решение владелицы — см. блок-комментарий вверху файла
    { value: 'творческая', label: 'Творческая — на моё усмотрение' },
  ],
};

/** Q0. Тайл «Скоро день рождения» показывается, только если в архиве
 *  реально есть кадры с этим поводом (тот же принцип, что и раньше — если тег
 *  когда-нибудь пропадёт из архива, тайл исчезнет сам, без правки кода). Два
 *  других тайла дерева не зависят от данных: они определяют ФОРМАТ, а не
 *  конкретный тег, и форматы «индивидуальная»/«парная»/«творческая» в архиве
 *  есть всегда (`STORYBOARD.md` § 5). */
function buildQ0(photos: StoryboardPhoto[]): QuestionDef {
  const occasionTags = new Set(photos.flatMap((p) => normalizeOccasionTags(p.настроение)));
  const tiles: Tile[] = [];
  if (occasionTags.has('день рождения')) {
    tiles.push({ value: 'день рождения', label: 'Скоро день рождения' });
  }
  tiles.push({ value: 'вайб', label: 'Вайб имеется' }, { value: 'любовь', label: 'Запечатлеть любовь' });
  return {
    id: 'повод',
    title: 'Какой у вас повод посниматься?',
    tiles,
  };
}

/**
 * Единственное место, которое знает форму дерева. `answers` — словарь
 * id→value уже данных ответов (история квиза). Возвращает следующий вопрос
 * или `null`, если пора считать результат.
 */
export function nextQuestionInTree(
  answers: Record<string, string>,
  photos: StoryboardPhoto[],
): QuestionDef | null {
  if (!('повод' in answers)) return buildQ0(photos);

  const povod = answers['повод'];

  if (povod === 'вайб') {
    if (!('формат' in answers)) return Q_VIBE_FORMAT;
    if (answers['формат'] === 'индивидуальная' && !('пол' in answers)) return Q_GENDER;
  }
  // повод === 'любовь' → формат жёстко «парная», вопроса нет (см. buildBriefAnswers)
  // повод === 'день рождения' → формат этой веткой вообще не используется

  if (!('материал' in answers)) return Q_MATERIAL;
  if (!('место' in answers)) return Q_PLACE;
  if (!('образ' in answers)) return Q_LOOK;
  return null;
}

/**
 * Сколько всего шагов будет на ПРОЙДЕННОМ пути — для «зажигающихся звёзд»
 * прогресса. `null`, пока это ещё не определено однозначно (ветка «вайб» до
 * ответа на Q1 может привести и к 5 шагам, и к 6 — с полом или без).
 */
export function estimateTotalSteps(answers: Record<string, string>): number | null {
  if (!('повод' in answers)) return null;
  const povod = answers['повод'];
  if (povod !== 'вайб') return 4; // повод + материал + место + образ
  if (!('формат' in answers)) return null;
  return answers['формат'] === 'индивидуальная' ? 6 : 5;
}

/** Собирает `BriefAnswers` для `pick.ts` из истории ответов дерева. */
export function buildBriefAnswers(answers: Record<string, string>): BriefAnswers {
  const povod = answers['повод'];
  const формат =
    povod === 'любовь'
      ? 'парная' // решение координатора — см. `nextQuestionInTree`
      : ((answers['формат'] as BriefAnswers['формат']) ?? 'индивидуальная'); // повод-ветка не использует формат вовсе, заглушка типа — см. pick.ts

  return {
    формат,
    материал: (answers['материал'] as BriefAnswers['материал']) ?? 'любой',
    место: (answers['место'] as BriefAnswers['место']) ?? 'неважно',
    образ: SKIP_LOOK, // редакция 4 не собирает конкретный тег образа — см. Q_LOOK
    повод: povod === 'день рождения' ? povod : OCCASION_NONE,
    пол: answers['пол'] as BriefAnswers['пол'],
  };
}
