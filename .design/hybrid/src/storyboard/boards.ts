/**
 * ДОСКИ PINTEREST → ВЕТКИ ДЕРЕВА — правка Ф34 (`FACTS.md`), пришла ДО того,
 * как редакция 4 (Ф33) была закончена, и правит именно способ показа
 * Pinterest внутри уже расписанного дерева, не отменяет само дерево.
 *
 * БЫЛО (Ф31/Ф32, редакции 1–3): шесть досок фиксированными вкладками на
 * ОДНОМ вопросе «образ». СТАЛО (Ф34): доски привязаны к КОНКРЕТНЫМ ответам
 * дерева и показываются НАКОПИТЕЛЬНО по всему пройденному пути на экране
 * результата — если путь прошёл через несколько ответов со своей доской,
 * показываются все накопленные доски разом, не одна.
 *
 * Таблица привязки — дословно из `FACTS.md` Ф34:
 *
 * | Доска | Привязана к |
 * |---|---|
 * | `мужские-съёмки` | ответ «парень» (ветка «в одиночку» → «парень») |
 * | `макияж-вояж-образ`, `луки-на-съемку` | ТОЛЬКО «девушка» — дословно «в
 * |   парную не стоит это тоже добавлять», к «вдвоём» НЕ подключать |
 * | `inspiration`, `восхищает` | ветка «Вайб имеется» целиком (все три
 * |   под-варианта верхнего уровня: одиночку/вдвоём/творческая) |
 * | `содержание`, `композиция` | ответ «в одиночку» сам по себе (до вопроса
 * |   про пол — накапливается с досками парня/девушки) |
 * | `запечатлеваем-любовь` | ветка «Запечатлеть любовь» целиком |
 *
 * Ветка «Скоро день рождения» — досок не названо вовсе, `boardsForAnswers`
 * возвращает пустой список, и экран результата этой ветки идёт без секции
 * Pinterest вообще (не пустая рамка — секции нет, см. `StoryboardApp.tsx`).
 *
 * `свет`/`цвет` — НЕ подключены (`open_question` OQ-24, как раньше OQ-23):
 * владелица просила привязать их «ко всем вариантам ответов с таким же
 * названием», но дерево Ф33 не задаёт ответов, буквально называемых
 * «свет»/«цвет» (материал — цифра/плёнка/всё сразу, место — дома/на улице/
 * в студии) — реализовывать домыслом, к чему именно это относится, запрещено
 * тем же правилом, что уже применялось к OQ-23.
 *
 * ПОРЯДОК И ДЕФОЛТНАЯ ВКЛАДКА — ПРАВКА Ф38, ОТМЕНЯЕТ ПОРЯДОК ВЫШЕ. Ф34
 * оставляла порядок на билдера («от общей ветки к узкой»); владелица прямо
 * поправила: «естественно, при выборе "парень" первым должен открываться
 * виджет "мужские съемки", а при "вдвоем" — "запечатлеваем любовь"». Порядок
 * теперь ОТ УЗКОЙ ВЕТКИ К ОБЩЕЙ — самый специфичный ответ даёт доску, которая
 * идёт первой в списке (и поэтому активна по умолчанию, `PinterestBoards.tsx`
 * стартует с `active=0`), общие «вайб»-доски (`inspiration`/`восхищает`)
 * теперь всегда в хвосте. Применено ко всем веткам одинаково, не только к
 * двум названным примерам, — иначе порядок был бы предсказуем в одних
 * случаях и произволен в других без причины.
 *
 * НОВАЯ ПРИВЯЗКА — «вдвоём» → `запечатлеваем-любовь` (не было в Ф34, там эта
 * доска стояла только у ветки «Запечатлеть любовь»). Доска не эксклюзивна
 * одной ветке — пара, снимающаяся «вайбово», и пара, снимающаяся ради
 * годовщины, естественно делят один источник вдохновения.
 */

export interface PinBoard {
  slug: string;
  label: string;
}

const CATALOG: Record<string, PinBoard> = {
  inspiration: { slug: 'inspiration', label: 'Inspiration' },
  восхищает: { slug: 'восхищает', label: 'Восхищает' },
  содержание: { slug: 'содержание', label: 'Содержание' },
  композиция: { slug: 'композиция', label: 'Композиция' },
  'мужские-съёмки': { slug: 'мужские-съёмки', label: 'Мужские съёмки' },
  'макияж-вояж-образ': { slug: 'макияж-вояж-образ', label: 'Макияж, вояж, образ' },
  'луки-на-съемку': { slug: 'луки-на-съемку', label: 'Луки на съёмку' },
  'запечатлеваем-любовь': { slug: 'запечатлеваем-любовь', label: 'Запечатлеваем любовь' },
};

export function boardsForAnswers(answers: Record<string, string>): PinBoard[] {
  const slugs: string[] = [];

  // порядок — от УЗКОГО ответа к ОБЩЕМУ (Ф38): самая специфичная доска первая
  // (и поэтому активна по умолчанию), общие «вайб»-доски всегда в хвосте
  if (answers['пол'] === 'парень') slugs.push('мужские-съёмки');
  if (answers['пол'] === 'девушка') slugs.push('макияж-вояж-образ', 'луки-на-съемку');
  if (answers['повод'] === 'любовь') slugs.push('запечатлеваем-любовь');
  if (answers['формат'] === 'парная') slugs.push('запечатлеваем-любовь'); // Ф38: новая привязка
  if (answers['формат'] === 'индивидуальная') slugs.push('содержание', 'композиция');
  if (answers['повод'] === 'вайб') slugs.push('inspiration', 'восхищает');

  /* Ф39 п.12 — «доски "макияж вояж образ" и "луки на съемку" при выборе
     варианта "парень" или "вдвоем" убери в самый конец всех досок»,
     ПОПРАВЛЕНО ЕЮ ЖЕ следом: «при выборе варианта ответа "парень" убери из
     досок "макияж вояж образ" и "луки на съемку"».

     Итог по двум сообщениям: «вдвоём» — доски есть, но последними; «парень»
     — досок нет вовсе. Поэтому условие ниже только про парную.

     ОТКУДА ВЗЯЛОСЬ «В КОНЕЦ», ЕСЛИ ИХ ТАМ НЕ БЫЛО. До первого сообщения обе
     доски висели строго на ответе «девушка» (условие выше): Ф34 прямо
     запрещала их парной — «в парную не стоит это тоже добавлять». Двигать в
     хвост было нечего, и первое сообщение прочитано как отмена запрета Ф34
     («пусть будут, но последними»). Второе сообщение это прочтение
     подтвердило от обратного: доски появились на пути «парень», она их там
     увидела и попросила убрать — а про «вдвоём» не сказала ничего, то есть
     там они остаются.

     Стоит ПОСЛЕ всех прочих `push`, включая общие «вайб»-доски: «в самый
     конец всех досок» — значит и после `inspiration`/`восхищает` тоже. */
  if (answers['формат'] === 'парная') {
    slugs.push('макияж-вояж-образ', 'луки-на-съемку');
  }

  // на случай, если один и тот же slug оказался в списке дважды (например
  // будущая ветка могла бы пересечься с «любовь» и «парная» одновременно) —
  // порядок первого вхождения сохраняется, дублей не показываем
  return Array.from(new Set(slugs)).map((s) => CATALOG[s]);
}
