/**
 * Типы фичи «Придумать съёмку» (`BRIEF-STORYBOARD.md`). Источник данных —
 * `.design/storyboard-manifest.json` (204 записи, `FACTS.md` Ф30), экспортированный
 * в `public/storyboard/manifest.json` скриптом `scripts/export-storyboard-photos.mjs`.
 *
 * Поля названы кириллицей, как и в исходном манифесте — это не стилевая
 * прихоть: так каждое поле здесь трассируется обратно к строке `FACTS.md` Ф30
 * без перевода имён туда-обратно.
 *
 * РЕДАКЦИЯ 4 (Ф33, `STORYBOARD.md` § 13) — ветвящееся дерево вопросов вместо
 * плоского набора. Новое здесь: `пол` (только для ветки «в одиночку» дерева),
 * `PlaceAnswer`/`LookAnswer` — типы ответов НОВЫХ формулировок вопросов
 * («дома/на улице/в студии», «да/ещё думаю»), не совпадающие один-в-один со
 * старыми типами архива (`PlaceCategory`) — сопоставление живёт в `pick.ts`
 * (`placeMatches`), само огрубление места объяснено там же и в STORYBOARD.md.
 */

export type FormatBucket = 'индивидуальная' | 'парная' | 'творческая';
export type Material = 'цифра' | 'пленка';
export type PlaceCategory = 'природа' | 'город' | 'студия';

/** Один экспортированный кадр — ровно то, что лежит в `public/storyboard/manifest.json`. */
export interface StoryboardPhoto {
  id: string;
  src: string;
  /** реальные пиксельные размеры экспорта — чтобы `<img width height>` не давал прыжков вёрстки */
  w: number;
  h: number;
  alt: string;
  материал: Material | null;
  /** нормализовано (см. export-storyboard-photos.mjs, normalizeFormat):
   *  «индивидуальная съемка» и «индивидуальная» сведены к одному значению */
  формат: FormatBucket | null;
  /** сырая подпись места из архива, для подписи под кадром (например «город, зима»,
   *  «мужская, город») — «мужская» здесь единственный источник фильтра по полу,
   *  отдельного поля под пол в архиве нет вовсе, см. `pick.ts` */
  место: string | null;
  /** огрубление места до трёх вариантов брифа — БОНУС для скоринга, не жёсткий фильтр */
  местоКатегория: PlaceCategory | null;
  /** кросс-тег «образ» — сырые значения, у большинства фото пусто (45/204 в исходнике).
   *  Редакция 4 больше не собирает конкретный тег «образ» вопросом (дерево владелицы
   *  спрашивает бинарно «уже есть готовый образ?»), поле и бонус-механика в `pick.ts`
   *  оставлены для целостности архитектуры, но с новым деревом всегда неактивны. */
  образ: string[];
  /** кросс-тег «повод» (было «настроение» в исходном манифесте), уже нормализован
   *  до категории без под-папки материала (export-storyboard-photos.mjs, normalizeOccasion) */
  настроение: string[];
  /** Ключ серии съёмки (Ф41): одна папка + подряд идущие номера кадров = один
   *  момент с одного ракурса. Считается при экспорте (там же граница правила),
   *  используется `pick.ts`, чтобы в одну раскадровку не попали три почти
   *  одинаковых кадра. Необязательное: манифест, собранный до Ф41, поля не
   *  несёт, и подбор в этом случае просто работает как раньше. */
  серия?: string;
  /** Пол снимаемого (Ф42) — из СТРУКТУРЫ архива: папки `девушка/` и `парень/`
   *  второго уровня. До Ф42 пола как поля не было вовсе, и он выковыривался
   *  подстрокой «мужская» из сырого `место` — на пересобранном владелицей
   *  дереве такой метки нет ни у одного файла, и чтение подстроки перестало
   *  находить что-либо. `null` = в кадре не один человек (парные) либо пол
   *  не назван (мини-сет повода, файлы в корне материала).
   *  Необязательное: манифест, собранный до Ф42, поля не несёт. */
  пол?: 'парень' | 'девушка';
  /** Кто именно вдвоём (Ф46) — папка третьего уровня: романтическая пара,
   *  две девушки или два парня. Формат отвечает на вопрос «сколько людей в
   *  кадре», состав — «кто они друг другу»; ветке «Запечатлеть любовь»
   *  нужен второй вопрос, а не первый. `null`/отсутствует у всего, что не
   *  «вдвоём», и у манифестов, собранных до Ф46. */
  ветка?: 'любовь' | 'вайб';
  /** Отпечаток СОДЕРЖИМОГО файла (Ф49). Один и тот же кадр владелица кладёт
   *  в несколько папок намеренно: он честно подходит и «дома», и «в студии»,
   *  а десять плёночных парных кадров стоят сразу в двух ветках. Манифест
   *  строится по путям, поэтому такой кадр даёт несколько записей с разными
   *  `id`, и подбор считал их разными фотографиями. Отпечаток — то
   *  единственное, по чему видно, что это одна и та же карточка; `pick.ts`
   *  не пускает два кадра с одним отпечатком в одну раскадровку.
   *  Необязательное: манифест, собранный до Ф49, поля не несёт. */
  отпечаток?: string;
}

/** Ответ на новый вопрос «где вы хотели бы провести съёмку?» (дерево Ф33 — дословно
 *  «дома | на улице | в студии»). Архив НЕ содержит бакета «дома» вовсе (только
 *  природа/город/студия, STORYBOARD.md § 2) — сопоставление с реальными категориями
 *  архива, огрубление задокументировано в `pick.ts` (`placeMatches`):
 *   - «в_студии» → местоКатегория === 'студия'
 *   - «дома» → тоже местоКатегория === 'студия' (ближайшее к дому — контролируемое
 *     помещение, других крытых категорий в архиве нет)
 *   - «на_улице» → местоКатегория === 'природа' ИЛИ 'город' (архив делит открытый
 *     воздух подробнее дерева владелицы, оба варианта читаются как «на улице»)
 *   - «неважно» — добавка билдера (как и раньше, «Пока не знаю»), дерево владелицы
 *     не предполагало этот вариант явно, но бонус-архитектура пригодна для него без
 *     дополнительной работы, и это удобно для мини-сета «день рождения», где места
 *     нет вовсе */
export type PlaceAnswer = 'дома' | 'на_улице' | 'в_студии' | 'неважно';

/** Ответ на новый вопрос «уже есть готовый образ?» — да/ещё думаю ведут на один и
 *  тот же экран результата (дерево Ф33), не влияет на подбор (см. комментарий у
 *  `образ` выше), используется только чтобы слегка настроить копирайт результата. */
export type LookAnswer = 'да' | 'ещё думаю';

/** Ответы брифа, собранные по дереву `questions.ts` в один объект для `pick.ts`.
 *  `образ` и `повод` — необязательные оси: `'неважно'`/`OCCASION_NONE` означают
 *  «не фильтровать», а не «фото без этого тега». `пол` — новое поле редакции 4,
 *  осмысленно только когда `формат === 'индивидуальная'` (ветка «в одиночку»
 *  дерева Ф33); для «девушка» фильтр не применяется вовсе (решение координатора,
 *  FACTS.md Ф33: «для „девушка“ — та же система, без этого фильтра»). */
export interface BriefAnswers {
  формат: FormatBucket;
  материал: Material | 'любой';
  место: PlaceAnswer;
  образ: string;
  повод: string;
  пол?: 'парень' | 'девушка';
  /** Ф46 — ветка «Запечатлеть любовь» просит только романтические пары.
   *  Задаётся `buildBriefAnswers` (`questions.ts`) и больше нигде: сам
   *  квиз про состав не спрашивает, это следствие выбранного повода. */
  ветка?: 'любовь' | 'вайб';
}

export const SKIP_LOOK = 'неважно';
export const OCCASION_NONE = 'без повода';
