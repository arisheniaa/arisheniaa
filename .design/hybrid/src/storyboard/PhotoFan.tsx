import { Fan } from '../Fan';
import type { FanPhoto } from '../Fan';
import type { StoryboardPhoto } from './types';
import { normalizeOccasionTags } from './pick';

/**
 * ВЕЕР РЕЗУЛЬТАТА РАСКАДРОВКИ — тонкая обёртка над общим `../Fan.tsx`.
 *
 * Вся механика (три состояния, тач/reduced-motion, клавиатура) переехала в
 * `Fan` при Ф40, когда тот же веер понадобился карточке «Творческая» на
 * главной. Здесь осталось ровно то, что знает про раскадровку и не имеет
 * смысла на главной:
 *
 *  · перевод `StoryboardPhoto` → `FanPhoto`;
 *  · `data-*` на каждой карточке (`data-format`/`data-material`/
 *    `data-place-category`/`data-place-raw`/`data-look`/`data-occasion`).
 *    Они НЕ декоративны: `scripts/selfcheck-storyboard.mjs` меряет по ним,
 *    что подбор действительно фильтрует по ответам дерева. Поэтому `Fan`
 *    принимает произвольный набор `data`, а не хардкодит эти шесть — на
 *    главной ни одного из них нет и быть не должно;
 *  · подпись группы для скринридера — здесь она про «мои съёмки», на главной
 *    про творческую съёмку.
 */
export function PhotoFan({ photos }: { photos: StoryboardPhoto[] }) {
  const items: FanPhoto[] = photos.map((p) => ({
    key: p.id,
    src: p.src,
    alt: p.alt,
    w: p.w,
    h: p.h,
    data: {
      'data-format': p.формат ?? '',
      'data-material': p.материал ?? '',
      'data-place-category': p.местоКатегория ?? '',
      'data-place-raw': p.место ?? '',
      'data-look': p.образ.join(','),
      'data-occasion': normalizeOccasionTags(p.настроение).join(','),
      // Ф41 — ключ серии на карточке: по нему самопроверка меряет, что в одну
      // раскадровку не попало два кадра одной съёмки с одного ракурса.
      'data-series': p.серия ?? '',
      // Ф42 — пол на карточке: по нему самопроверка меряет, что ответ
      // «девушка» не приносит ни одного мужского кадра.
      'data-gender': p.пол ?? '',
    },
  }));

  return (
    <Fan
      photos={items}
      /* `eager` ЯВНО (Ф41, по умолчанию у `Fan` теперь `lazy`): экран
         результата появляется по нажатию, уже прокрученным к себе, и веер
         на нём виден сразу. Ленивая загрузка дала бы пустые рамки ровно в
         тот момент, ради которого человек прошёл весь квиз. Кадров здесь
         шесть, вес каждого ~30 КБ — цена мала, выигрыш заметен. */
      loading="eager"
      label={`Фотографии из моих съёмок, ${photos.length} штук — наведите курсор или сфокусируйте, чтобы увидеть все целиком`}
    />
  );
}
