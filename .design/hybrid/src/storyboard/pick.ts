import type { BriefAnswers, PlaceCategory, StoryboardPhoto } from './types';
import { OCCASION_NONE, SKIP_LOOK } from './types';

/**
 * АЛГОРИТМ ПОДБОРА — `BRIEF-STORYBOARD.md` § 2/раздел о задаче билдера:
 * «раз теги местами пустые/частичные — реализуй разумное ослабление критериев
 * (например точное совпадение формат+материал всегда, место/образ — бонус к
 * релевантности, а не жёсткий фильтр, иначе многие комбинации ответов дадут
 * пустой результат)».
 *
 * МАТЕРИАЛ — ЖЁСТКИЙ ФИЛЬТР БЕЗ ОСЛАБЛЕНИЯ, ПРАВКА Ф37 (ОТМЕНЯЕТ ЧАСТЬ
 * АРХИТЕКТУРЫ РЕДАКЦИИ 4). Раньше материал вёл себя как формат-но-с-запасным-
 * планом: при пуле меньше `MIN_POOL` тихо снимался, и читатель, выбравший
 * «плёнка», мог увидеть цифровые кадры с оговоркой «кадров мало». Владелица
 * прямо это отменила: «пользователь хочет увидеть референсы на плёнку, а не
 * на цифру. не приписывай, что фотографий недостаточно». Теперь материал —
 * такой же безусловный жёсткий фильтр, как формат: строгий пул может быть
 * меньше `count` или даже пустым (тогда работает общее состояние «нет
 * результатов», уже предусмотренное `StoryboardApp.tsx`), но никогда не
 * подменяется молча кадрами другого материала.
 *
 * ЖЁСТКИЙ ФИЛЬТР:
 *  1. `формат` — всегда точно. Бакеты (`export-storyboard-photos.mjs`,
 *     normalizeFormat) обеспечивают достаточный запас на любой из трёх
 *     вариантов — пустого результата по одному формату не бывает.
 *  2. `материал` — всегда точно, без ослабления (см. выше).
 *  3. `пол` (только формат «индивидуальная», значение «парень») — точно, но
 *     С ОСЛАБЛЕНИЕМ (единственная ось, для которой оно осталось): тег
 *     «мужская» несёт 6 файлов во всём архиве (4 цифра + 2 плёнка,
 *     `цифра/парень/`, `пленка/парень/` — новая структура Ф37, заменила
 *     старую подпапку «мужская, город» с двумя файлами из Ф33). 6 всё ещё
 *     на грани `MIN_POOL`, а при уточнении материалом (например «парень» +
 *     «плёнка», пул 2) фильтр по полу может сняться — это честно сообщается
 *     читателю (`relaxedGender`), не молча. Снятый фильтр не значит потерянный
 *     сигнал: реальные кадры с меткой «мужская» получают БОНУС (+2) в общем
 *     скоринге ниже, поэтому они гарантированно всплывают в топ выдачи, даже
 *     когда сам фильтр снят.
 *
 * БОНУС, НЕ ФИЛЬТР (место, образ, и — только когда «пол» запрошен — сама метка
 * «мужская» после её возможного ослабления):
 *  Тег есть только у части архива (образ — 53/204, `FACTS.md` Ф30). Жёсткий
 *  фильтр по нему оставлял бы клиента с пустым результатом на большинстве
 *  комбинаций ответов. Вместо этого — очки релевантности: совпадение поднимает
 *  кадр в выдаче, отсутствие тега не исключает кадр из пула.
 *
 * МЕСТО — ОГРУБЛЕНИЕ ДВАЖДЫ. Реальные подпапки архива уже огрублены до трёх
 * категорий (`местоКатегория`: природа/город/студия, `export-storyboard-
 * photos.mjs`). Новое дерево (Ф33) задаёт СВОИ три варианта словами владелицы
 * — «дома»/«на улице»/«в студии» — которые не совпадают с этим списком один в
 * один (архив не знает слова «дома» вовсе). Сопоставление — `placeMatches()`
 * ниже, задокументировано там же и в STORYBOARD.md § 13.
 *
 * НАХОДКА ПРИ САМОПРОВЕРКЕ РЕД. 1 — «повод» не может быть бонусом ВНУТРИ пула
 * формата. Все 20 фото с поводом «день рождения» (`FACTS.md` Ф30) —
 * САМОСТОЯТЕЛЬНЫЙ мини-сет: у них `формат: null`. Жёсткий фильтр по формату
 * идёт первым и применяется всегда — значит эти 20 фото исключались бы из
 * пула ДО того, как бонус за повод успел бы их поднять.
 *
 *   ПОВОД — НЕ БОНУС, А ОТДЕЛЬНАЯ ВЕТКА. Если ответ на «Какой у вас повод
 *   посниматься?» — «день рождения», подбор идёт по мини-сету этого повода, в
 *   обход фильтра по формату (формату взяться неоткуда — у этих фото его нет).
 *   Материал внутри повода реально существует (15 цифра / 5 плёнка) и участвует
 *   ТЕМ ЖЕ безусловным жёстким фильтром, что и в основном пайплайне (Ф37) — не
 *   бонусом, как было в редакции 1: новое дерево Ф33 явно задаёт материал как
 *   вопрос-плитку и внутри ветки повода тоже, что честнее читать как фильтр, а
 *   не подсказку. Место и образ у этого мини-сета
 *   отсутствуют ПОЛНОСТЬЮ (0 из 20 несут любой из тегов) — дерево Ф33 всё
 *   равно просит эти вопросы и здесь (дословно, не сокращать), поэтому они
 *   участвуют как бонус наравне с остальными ветками, просто НИКОГДА не
 *   находят совпадения на этом мини-сете; экран честно объясняет это отдельной
 *   строкой, а не молчит о том, что ответы не сработали.
 *
 * Небольшой случайный довесок (`rng() * 0.75`) разводит кадры с одинаковым
 * счётом: без него один и тот же набор ответов всегда возвращал бы первые N
 * кадров архива по порядку файлов, что не раскадровка, а листинг папки.
 */

export interface PickResult {
  photos: StoryboardPhoto[];
  /** фильтр по полу («парень») был снят из-за нехватки кадров под метку «мужская» —
   *  архив несёт её всего у 2 файлов на плёнку, снятие возможно и на плёнке, см.
   *  комментарий выше */
  relaxedGender: boolean;
  /** подбор шёл по отдельному мини-сету повода в обход фильтра формата — см. комментарий выше */
  occasionOverride: boolean;
  /** сколько кандидатов было в пуле ДО отбора топ-N — для самопроверки/отладки */
  poolSize: number;
}

const MIN_POOL = 6;

export function normalizeOccasionTags(tags: string[]): string[] {
  return Array.from(new Set(tags.map((t) => t.split(' / ')[0])));
}

/** Сопоставление нового вопроса «где вы хотели бы провести съёмку?» (дома/на
 *  улице/в студии — дословно дерево Ф33) с реальными категориями архива
 *  (`местоКатегория`: природа/город/студия). Огрубление, не факт:
 *   - «в_студии» → студия (точное совпадение)
 *   - «дома» → тоже студия: единственная крытая, контролируемая категория,
 *     которая есть в архиве — ближе к «дома», чем открытый воздух
 *   - «на_улице» → природа ИЛИ город: дерево владелицы не делит открытый
 *     воздух подробнее, а архив делит — оба читаются как «на улице»
 *   - «неважно» — никогда не совпадает (бонус не начисляется намеренно) */
export function placeMatches(answer: BriefAnswers['место'], category: PlaceCategory | null): boolean {
  if (!category) return false;
  if (answer === 'в_студии' || answer === 'дома') return category === 'студия';
  if (answer === 'на_улице') return category === 'природа' || category === 'город';
  return false;
}

/** Метка «мужская» — часть СЫРОГО поля `место` (архив её никогда не хранил
 *  отдельным тегом пола, `FACTS.md` Ф33), не `местоКатегория`. */
function isMale(photo: StoryboardPhoto): boolean {
  return !!photo.место && photo.место.includes('мужская');
}

/** Общий скоринг: бонус места + бонус образа (сейчас всегда неактивен новым
 *  деревом, оставлен архитектурно) + опциональный бонус «мужская», когда
 *  фильтр по полу запрошен (даже если сам фильтр в итоге снят ослаблением —
 *  см. блок-комментарий вверху файла) + случайный довесок для развода ничьих. */
function scorePool(
  pool: StoryboardPhoto[],
  answers: BriefAnswers,
  wantsGender: boolean,
  rng: () => number,
) {
  return pool.map((photo) => {
    let score = 0;
    if (placeMatches(answers.место, photo.местоКатегория)) score += 2;
    if (answers.образ !== SKIP_LOOK && photo.образ.includes(answers.образ)) score += 2;
    if (wantsGender && isMale(photo)) score += 2;
    return { photo, score: score + rng() * 0.75 };
  });
}

function topN(
  scored: { photo: StoryboardPhoto; score: number }[],
  count: number,
): StoryboardPhoto[] {
  return [...scored].sort((a, b) => b.score - a.score).slice(0, Math.min(count, scored.length)).map((s) => s.photo);
}

export function pickStoryboard(
  all: StoryboardPhoto[],
  answers: BriefAnswers,
  count = 6,
  rng: () => number = Math.random,
): PickResult {
  /* ═══ ВЕТКА ПОВОДА — см. блок-комментарий вверху файла ═══ */
  if (answers.повод !== OCCASION_NONE) {
    const occasionPool = all.filter((p) => p.настроение.includes(answers.повод));
    if (occasionPool.length > 0) {
      // материал — жёсткий фильтр и здесь, без ослабления (Ф37: «пользователь хочет
      // увидеть референсы на плёнку, а не на цифру», см. блок-комментарий вверху файла)
      const pool =
        answers.материал !== 'любой'
          ? occasionPool.filter((p) => p.материал === answers.материал)
          : occasionPool;
      const scored = scorePool(pool, answers, false, rng);
      return {
        photos: topN(scored, count),
        relaxedGender: false,
        occasionOverride: true,
        poolSize: pool.length,
      };
    }
    // тег заявлен в вопросе, но в архиве под него ничего нет — падаем в обычный конвейер
  }

  /* ═══ ОБЫЧНЫЙ ПАЙПЛАЙН — формат и материал жёстко, пол — с ослаблением ═══
     Материал НЕ ослабляется (Ф37, отменяет прежнее «снимается материал первым»):
     владелица прямо попросила не подменять плёнку цифрой и не показывать сообщение
     о нехватке — если строгий пул мал или пуст, честно показываются те кадры, что
     есть (`topN` уже отдаёт `Math.min(count, pool.length)`, не дополняет чужим
     материалом). */
  const byFormat = all.filter((p) => p.формат === answers.формат);

  const wantsMaterial = answers.материал !== 'любой';
  const wantsGender = answers.формат === 'индивидуальная' && answers.пол === 'парень';

  let activeGender = wantsGender;

  const computePool = () =>
    byFormat.filter(
      (p) =>
        (!wantsMaterial || p.материал === answers.материал) && (!activeGender || isMale(p)),
    );

  let pool = computePool();
  let relaxedGender = false;

  // ослабление снимает только фильтр по полу — материал остаётся жёстким всегда
  if (pool.length < MIN_POOL && activeGender) {
    activeGender = false;
    relaxedGender = true;
    pool = computePool();
  }

  const scored = scorePool(pool, answers, wantsGender, rng);

  return {
    photos: topN(scored, count),
    relaxedGender,
    occasionOverride: false,
    poolSize: pool.length,
  };
}
