import type { BriefAnswers, StoryboardPhoto } from './types';
import { OCCASION_NONE, SKIP_LOOK } from './types';

/**
 * АЛГОРИТМ ПОДБОРА — `BRIEF-STORYBOARD.md` § 2/раздел о задаче билдера:
 * «раз теги местами пустые/частичные — реализуй разумное ослабление критериев
 * (например точное совпадение формат+материал всегда, место/образ — бонус к
 * релевантности, а не жёсткий фильтр, иначе многие комбинации ответов дадут
 * пустой результат)».
 *
 * ЖЁСТКИЙ ФИЛЬТР:
 *  1. `формат` — всегда точно. Бакеты (`export-storyboard-photos.mjs`,
 *     normalizeFormat) обеспечивают ≥21 кадр на любой из трёх вариантов —
 *     пустого результата по одному формату не бывает.
 *  2. `материал` — точно, НО с автоматическим ослаблением: если строгое
 *     совпадение формат+материал даёт МЕНЬШЕ `MIN_POOL` кадров (реальный
 *     случай — «творческая» + «плёнка»: в архиве творческих плёночных
 *     съёмок нет вовсе, 0 из 62), фильтр по материалу снимается целиком и
 *     подбор идёт по всему формату. Флаг `relaxedMaterial` в результате —
 *     чтобы страница могла честно сказать об этом, а не притвориться, что
 *     план сработал как задумано (см. `Results.tsx`).
 *
 * БОНУС, НЕ ФИЛЬТР (место, образ):
 *  Тег есть только у части архива (образ — 53/204, `FACTS.md` Ф30). Жёсткий
 *  фильтр по нему оставлял бы клиента с пустым результатом на большинстве
 *  комбинаций ответов. Вместо этого — очки релевантности: совпадение поднимает
 *  кадр в выдаче, отсутствие тега не исключает кадр из пула.
 *
 * НАХОДКА ПРИ САМОПРОВЕРКЕ — «повод» не может быть бонусом ВНУТРИ пула
 * формата. Все 20 фото с поводом «день рождения» (`FACTS.md` Ф30) —
 * САМОСТОЯТЕЛЬНЫЙ мини-сет: у них `формат: null` (см. `export-storyboard-
 * photos.mjs`). Жёсткий фильтр по формату идёт первым и применяется всегда —
 * значит эти 20 фото исключались бы из пула ДО того, как бонус за повод успел
 * бы их поднять. Вопрос «Есть повод?» был бы декоративным: отвечай на него
 * как угодно, на выдачу это не влияло бы никогда. Обнаружено не мнением, а
 * прогоном (`node -e` подсчёт формата у фото с тегом настроения — 0 из 20
 * имеют формат), поэтому решение не «замять», а переработать конвейер:
 *
 *   ПОВОД — НЕ БОНУС, А ОТДЕЛЬНАЯ ВЕТКА. Если ответ на «Есть повод?» — реальное
 *   значение (не «без повода»), подбор идёт ЦЕЛИКОМ по мини-сету этого повода,
 *   в обход фильтра по формату (формату взяться неоткуда — у этих фото его
 *   нет, и выдумывать его запрещено, `FACTS.md` Ф30: «пустое поле остаётся
 *   пустым»). Материал внутри повода — единственный тег, который у этих фото
 *   реально есть, поэтому именно он и участвует бонусом. Экран сообщает об
 *   этом прямо (`Results.tsx`, `occasionOverride`), а не притворяется, что
 *   вопросы «кто в кадре» и «где» были применены. Флоу в `StoryboardApp.tsx`
 *   ставит вопрос «Есть повод?» ПЕРВЫМ и, если выбран реальный повод,
 *   пропускает остальные вопросы — не тратит время читателя на форматы,
 *   которые всё равно не будут учтены.
 *
 * Небольшой случайный довесок (`rng() * 0.75`) разводит кадры с одинаковым
 * счётом (у большинства фото счёт 0 — тегов для бонуса нет): без него один и
 * тот же набор ответов всегда возвращал бы первые N кадров архива по порядку
 * файлов, что не раскадровка, а листинг папки.
 */

export interface PickResult {
  photos: StoryboardPhoto[];
  /** материал был снят как фильтр из-за нехватки кадров под точное сочетание формат+материал */
  relaxedMaterial: boolean;
  /** подбор шёл по отдельному мини-сету повода в обход фильтра формата — см. комментарий выше */
  occasionOverride: boolean;
  /** сколько кандидатов было в пуле ДО отбора топ-N — для самопроверки/отладки */
  poolSize: number;
}

const MIN_POOL = 6;

export function normalizeOccasionTags(tags: string[]): string[] {
  return Array.from(new Set(tags.map((t) => t.split(' / ')[0])));
}

export function pickStoryboard(
  all: StoryboardPhoto[],
  answers: BriefAnswers,
  count = 6,
  rng: () => number = Math.random,
): PickResult {
  /* ветка повода — см. комментарий выше. Проверяется ПЕРВОЙ и, если в архиве
     реально есть фото с этим поводом, замещает обычный конвейер целиком. */
  if (answers.повод !== OCCASION_NONE) {
    const occasionPool = all.filter((p) => p.настроение.includes(answers.повод));
    if (occasionPool.length > 0) {
      const scored = occasionPool.map((photo) => ({
        photo,
        // материал — единственный тег, который у мини-сета повода реально есть
        score: (answers.материал !== 'любой' && photo.материал === answers.материал ? 2 : 0) +
          rng() * 0.75,
      }));
      scored.sort((a, b) => b.score - a.score);
      return {
        photos: scored.slice(0, Math.min(count, scored.length)).map((s) => s.photo),
        relaxedMaterial: false,
        occasionOverride: true,
        poolSize: occasionPool.length,
      };
    }
    // тег заявлен в вопросе, но в архиве под него ничего нет — падаем в обычный конвейер
  }

  const byFormat = all.filter((p) => p.формат === answers.формат);

  let pool = byFormat;
  let relaxedMaterial = false;
  if (answers.материал !== 'любой') {
    const strict = byFormat.filter((p) => p.материал === answers.материал);
    if (strict.length >= MIN_POOL) {
      pool = strict;
    } else {
      relaxedMaterial = true;
      pool = byFormat;
    }
  }

  const scored = pool.map((photo) => {
    let score = 0;
    if (answers.место !== 'неважно' && photo.местоКатегория === answers.место) score += 2;
    if (answers.образ !== SKIP_LOOK && photo.образ.includes(answers.образ)) score += 2;
    return { photo, score: score + rng() * 0.75 };
  });

  scored.sort((a, b) => b.score - a.score);
  const photos = scored.slice(0, Math.min(count, scored.length)).map((s) => s.photo);

  return { photos, relaxedMaterial, occasionOverride: false, poolSize: pool.length };
}
