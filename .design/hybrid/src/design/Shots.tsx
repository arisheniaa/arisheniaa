/**
 * СТОПКА ЭКРАНОВ РАБОТЫ — портфолио ветки дизайна (Ф76).
 *
 * Владелица: «сделаем раскладку как в фото-разделе в самом начале (чтобы
 * скрины лежали друг на дружке как фотографии лежат стопкой на главной)…
 * при нажатии на стопку скриншоты бы разъезжались веером в сторону на
 * ноутбуке, и вниз на мобильной. сделай возможность нажать на скриншоты,
 * чтобы рассмотреть получше». И отдельно: «на мобильной версии оставь только
 * скриншоты с мобильной версии сайтов, а в десктопной — только скриншоты с
 * ноутбука».
 *
 * ПОЧЕМУ НЕ `Fan.tsx`, КОТОРЫЙ УЖЕ ЕСТЬ. Тот веер живёт на фотоветке (услуги
 * и раскадровка) и раскрывается НАВЕДЕНИЕМ, а на таче раскладывает кадры
 * сразу. Здесь нужны другие правила: раскрытие по нажатию, направление зависит
 * от ширины экрана, и наборы кадров у ширин РАЗНЫЕ. Ветвить общий компонент
 * четырьмя новыми условиями значило бы рисковать тем, что уже работает на
 * фотоветке, ради чужой механики. Общее у них — только идея стопки.
 *
 * НАБОРЫ КАДРОВ НЕ ПЕРЕСЕКАЮТСЯ. На широком экране показываются снимки
 * сайта, снятые в ширине ноутбука, на телефоне — снятые в ширине телефона.
 * Рендерится ТОЛЬКО подходящий набор: браузер не скачивает то, чего не
 * покажет, — на мобильной сети это пять лишних файлов на каждую работу.
 *
 * ТРИ СОСТОЯНИЯ:
 *  1. СТОПКА — кадры лежат друг на друге со сдвигом и лёгким поворотом, как
 *     снимки на первом экране фотоветки. Видно верхний.
 *  2. РАЗЛОЖЕНО — нажатие раскладывает: вбок на широком экране, вниз на
 *     телефоне. Анимация одна и та же, меняется только ось.
 *  3. КРУПНО — нажатие на разложенный кадр открывает его во весь экран.
 *
 * ДОСТУПНОСТЬ. Пока стопка сложена, в порядке табуляции ровно одна кнопка —
 * сама стопка: остальные кадры не видны, и водить по ним фокус означало бы
 * гонять читателя по невидимому. Открытый крупный кадр — диалог: фокус
 * уходит на кнопку закрытия, Esc закрывает, фон под ним глохнет.
 */
import { useCallback, useEffect, useLayoutEffect, useRef, useState } from 'react';
import { createPortal } from 'react-dom';

export type Кадр = { src: string; alt: string };

/** Ширина, с которой показываются кадры ноутбука. Та же граница, что у
 *  раскладок страницы (`md:` в Tailwind) — сайт не должен менять правило
 *  ширины в двух местах по-разному. */
const ШИРОКИЙ = '(min-width: 768px)';

/* ═══ ПЕРЕЛЁТ КАДРОВ МЕЖДУ РАСКЛАДКАМИ ══════════════════════════════════
   «Сделай анимацию раскрытия стопки в карусель плавной, как весь сайт».

   Между стопкой и лентой у кадра меняется ВСЁ: он переезжает из коробки с
   абсолютными слоями в поток ленты, у него другой размер и другой поворот.
   Обычным переходом это не анимируется — переход умеет менять свойства
   одного узла, а тут узлы разные и раскладка другая.

   Приём известный: замерить положение ДО смены, замерить ПОСЛЕ, поставить
   кадру обратный сдвиг (как будто он ещё на старом месте) и отпустить его
   в ноль с переходом. Глазу это читается как «кадры разъехались из стопки
   в ряд», хотя на деле разметка сменилась мгновенно.

   Замер и сдвиг ставятся ДО отрисовки кадра (`useLayoutEffect`), иначе
   браузер успел бы показать конечное положение и перелёт читался бы
   рывком назад.

   Длительность 520 мс и общая кривая `--ease-out` — между складыванием
   папок (420) и проявлением секций (620): движение крупнее первого, но
   мельче входа целой секции. При выключенном движении перелёта нет,
   раскладка меняется сразу. */
function useПерелёт() {
  const было = useRef<DOMRect[] | null>(null);
  const узлы = useRef<(HTMLElement | null)[]>([]);

  const запомнить = useCallback(() => {
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
    было.current = узлы.current
      .filter(Boolean)
      .map((el) => (el as HTMLElement).getBoundingClientRect());
  }, []);

  useLayoutEffect(() => {
    const старые = было.current;
    было.current = null;
    if (!старые) return;
    const новые = узлы.current.filter(Boolean) as HTMLElement[];
    новые.forEach((el, i) => {
      const с = старые[i];
      if (!с) return;
      const н = el.getBoundingClientRect();
      const dx = с.left - н.left;
      const dy = с.top - н.top;
      const k = н.width ? с.width / н.width : 1;
      if (Math.abs(dx) < 1 && Math.abs(dy) < 1 && Math.abs(k - 1) < 0.01) return;
      el.style.transition = 'none';
      el.style.transform = `translate(${dx}px, ${dy}px) scale(${k})`;
    });
    /* Два кадра ожидания, а не один: первый нужен браузеру, чтобы принять
       обратный сдвиг как исходное положение. Отпустив его в том же кадре,
       получим прыжок без анимации. */
    requestAnimationFrame(() => {
      requestAnimationFrame(() => {
        новые.forEach((el, i) => {
          /* МЕДЛЕННО И ПО ОЧЕРЕДИ («должны разъезжаться очень плавно»,
             «плавно разъезжались вправо»).

             880 мс вместо прежних 520: движение крупное — кадр проходит
             почти всю ширину колонки, — и на короткой выдержке оно
             читалось рывком, а не разъездом.

             Задержка 70 мс на каждый следующий кадр — то, что даёт
             НАПРАВЛЕНИЕ. Стопка стоит по центру, и без задержки кадры
             разъезжаются в обе стороны разом; с ней первый трогается
             раньше, последний позже, и глаз читает движение как волну
             вправо. Тот же приём, что у лестницы задержек при появлении
             секций (`--stagger`), только шаг крупнее: там строки текста,
             здесь экраны.

             Кривая `--ease-soft` вместо `--ease-out`: у неё пологий вход и
             долгий выкат — кадр не выстреливает с места, а трогается. */
          el.style.transition = `transform 880ms var(--ease-soft) ${i * 70}ms`;
          el.style.transform = '';
        });
      });
    });
  });

  return { запомнить, узлы };
}

export function Shots({
  ноутбук,
  телефон,
  работа,
}: {
  ноутбук: readonly Кадр[];
  телефон: readonly Кадр[];
  /** Имя работы — попадает в подписи кнопок: «показать экраны сайта Toto
   *  Shiro». Без него кнопки трёх работ звучали бы одинаково. */
  работа: string;
}) {
  /* Ширина считается один раз до первого кадра и потом слушается: поворот
     телефона и перетаскивание окна между экранами меняют набор кадров. */
  const [широкий, setШирокий] = useState(() => window.matchMedia(ШИРОКИЙ).matches);
  useEffect(() => {
    const mq = window.matchMedia(ШИРОКИЙ);
    const наСмену = () => setШирокий(mq.matches);
    mq.addEventListener('change', наСмену);
    return () => mq.removeEventListener('change', наСмену);
  }, []);

  const кадры = широкий ? ноутбук : телефон;
  const [разложено, setРазложено] = useState(false);
  const перелёт = useПерелёт();
  const [крупно, setКрупно] = useState<number | null>(null);

  /* Смена ширины складывает стопку обратно: раскладка другая, набор кадров
     другой, и оставлять её разложенной значило бы показать веер из кадров,
     которых читатель не открывал. */
  useEffect(() => {
    setРазложено(false);
    setКрупно(null);
  }, [широкий]);

  return (
    <div
      className={`shots${разложено ? ' is-open' : ''}${широкий ? '' : ' shots--m'}`}
    >
      {/* ОДНА РАЗМЕТКА НА ОБА СОСТОЯНИЯ, меняются только классы.

          Раньше стопка и лента были ДВУМЯ разными деревьями, и React при
          раскрытии выбрасывал одни узлы и создавал другие. Отсюда вспышка,
          на которую пожаловалась владелица: новая картинка секунду не
          отрисована, и сквозь неё видно подложку кадра — светлый
          прямоугольник вместо снимка.

          Теперь узлы те же: у кадра меняется только класс, картинка
          остаётся той же самой и заново не грузится. Вспышке взяться
          неоткуда.

          Раскладка переключается стилями (стопка — слои абсолютом, лента —
          строка с прокруткой), а перелёт между ними по-прежнему считает
          `useПерелёт`: положение до, положение после, обратный сдвиг. */}
      <div
        className={`shots-band${разложено ? ' is-rail' : ''}`}
        role={разложено ? 'group' : undefined}
        aria-label={разложено ? `Экраны сайта ${работа}` : undefined}
      >
        {кадры.map((к, i) => (
          <div key={к.src} className="shots-cell" style={{ ['--i' as string]: i }}>
            <button
              type="button"
              /* Перелёт вешается на КАРТОЧКУ, а не на ячейку. У ячейки свой
                 сдвиг стопки в стилях, и обратный сдвиг затёр бы его: кадры
                 поехали бы из неверного места. */
              ref={(el) => {
                перелёт.узлы.current[i] = el;
              }}
              className="shots-item"
              /* В сложенной стопке в порядке табуляции одна кнопка —
                 верхняя: остальные кадры под ней, и водить по ним фокус
                 означало бы гонять читателя по невидимому. */
              tabIndex={разложено || i === 0 ? 0 : -1}
              aria-hidden={разложено || i === 0 ? undefined : true}
              aria-label={
                разложено
                  ? `${к.alt}. Открыть крупно`
                  : `Показать экраны сайта ${работа}: ${кадры.length} кадров`
              }
              onClick={() => {
                if (разложено) {
                  setКрупно(i);
                  return;
                }
                перелёт.запомнить();
                setРазложено(true);
              }}
            >
              <img
                src={к.src}
                alt={разложено ? к.alt : ''}
                width={широкий ? 1200 : 1170}
                height={широкий ? 750 : 2080}
                className="frame block h-full w-full object-cover"
                loading="lazy"
                decoding="async"
                draggable={false}
              />
            </button>
          </div>
        ))}
      </div>
      {разложено ? (
        <p className="shots-fold">
          <button
            type="button"
            className="link-minor"
            onClick={() => {
              перелёт.запомнить();
              setРазложено(false);
            }}
          >
            сложить
          </button>
        </p>
      ) : null}

      {крупно !== null ? (
        <Крупно
          кадры={кадры}
          номер={крупно}
          листать={setКрупно}
          закрыть={() => setКрупно(null)}
        />
      ) : null}
    </div>
  );
}

/**
 * Кадр во весь экран. Портал в `body`: иначе увеличенный снимок остался бы
 * внутри колонки работы и обрезался бы её границами.
 */
function Крупно({
  кадры,
  номер,
  листать,
  закрыть,
}: {
  кадры: readonly Кадр[];
  номер: number;
  листать: (i: number) => void;
  закрыть: () => void;
}) {
  const кнопка = useRef<HTMLButtonElement>(null);
  const кадр = кадры[номер];

  /* ПЕРЕЛИСТЫВАНИЕ ВНУТРИ ОТКРЫТОГО КАДРА — не украшение, а следствие того,
     что веер небольшой: у нижних кадров наружу выходит полоска в десятую
     часть ширины, и попасть по ней пальцем трудно (на телефоне это порядка
     двадцати пикселей — вдвое меньше комфортной зоны касания). Открыв любой
     кадр, читатель теперь доходит до остальных стрелками, клавишами или
     кнопками — веер остаётся мелким, а кадры доступными.
     По кругу: с последнего вперёд — к первому. Пять кадров, тупик в конце
     ряда раздражал бы на ровном месте. */
  const шаг = useCallback(
    (куда: number) => листать((номер + куда + кадры.length) % кадры.length),
    [листать, номер, кадры.length],
  );

  const наКлавишу = useCallback(
    (e: KeyboardEvent) => {
      if (e.key === 'Escape') закрыть();
      if (e.key === 'ArrowRight') шаг(1);
      if (e.key === 'ArrowLeft') шаг(-1);
    },
    [закрыть, шаг],
  );

  useEffect(() => {
    /* Фокус уходит на кнопку закрытия: читатель клавиатурой должен попасть в
       открытый кадр, а не остаться позади него. Прокрутка страницы под
       кадром запирается — иначе фон едет вместе с жестом по картинке. */
    кнопка.current?.focus();
    const doc = document.documentElement;
    const было = doc.style.overflow;
    doc.style.overflow = 'hidden';
    window.addEventListener('keydown', наКлавишу);
    return () => {
      doc.style.overflow = было;
      window.removeEventListener('keydown', наКлавишу);
    };
  }, [наКлавишу]);

  return createPortal(
    <div className="shots-zoom" role="dialog" aria-modal="true" aria-label={кадр.alt}>
      {/* Нажатие мимо кадра закрывает — привычный жест. Сам кадр нажатие не
          закрывает: по нему могут водить пальцем, разглядывая. */}
      <button type="button" className="shots-zoom-bg" aria-label="Закрыть" onClick={закрыть} />
      <img src={кадр.src} alt={кадр.alt} className="shots-zoom-img" decoding="async" />
      <button ref={кнопка} type="button" className="shots-zoom-close" onClick={закрыть}>
        закрыть
      </button>
      <button
        type="button"
        className="shots-zoom-nav shots-zoom-prev"
        aria-label="Предыдущий экран"
        onClick={() => шаг(-1)}
      >
        ←
      </button>
      <button
        type="button"
        className="shots-zoom-nav shots-zoom-next"
        aria-label="Следующий экран"
        onClick={() => шаг(1)}
      >
        →
      </button>
      <p className="shots-zoom-count t-mono">
        {номер + 1} / {кадры.length}
      </p>
    </div>,
    document.body,
  );
}
