/**
 * СТОПКА ЭКРАНОВ РАБОТЫ — портфолио ветки дизайна (Ф76).
 *
 * Владелица: «сделаем раскладку как в фото-разделе в самом начале (чтобы
 * скрины лежали друг на дружке как фотографии лежат стопкой на главной)…
 * при нажатии на стопку скриншоты бы разъезжались веером в сторону на
 * ноутбуке, и вниз на мобильной. сделай возможность нажать на скриншоты,
 * чтобы рассмотреть получше». И отдельно: «на мобильной версии оставь только
 * скриншоты с мобильной версии сайтов, а в десктопной — только скриншоты с
 * ноутбука».
 *
 * ПОЧЕМУ НЕ `Fan.tsx`, КОТОРЫЙ УЖЕ ЕСТЬ. Тот веер живёт на фотоветке (услуги
 * и раскадровка) и раскрывается НАВЕДЕНИЕМ, а на таче раскладывает кадры
 * сразу. Здесь нужны другие правила: раскрытие по нажатию, направление зависит
 * от ширины экрана, и наборы кадров у ширин РАЗНЫЕ. Ветвить общий компонент
 * четырьмя новыми условиями значило бы рисковать тем, что уже работает на
 * фотоветке, ради чужой механики. Общее у них — только идея стопки.
 *
 * НАБОРЫ КАДРОВ НЕ ПЕРЕСЕКАЮТСЯ. На широком экране показываются снимки
 * сайта, снятые в ширине ноутбука, на телефоне — снятые в ширине телефона.
 * Рендерится ТОЛЬКО подходящий набор: браузер не скачивает то, чего не
 * покажет, — на мобильной сети это пять лишних файлов на каждую работу.
 *
 * ТРИ СОСТОЯНИЯ:
 *  1. СТОПКА — кадры лежат друг на друге со сдвигом и лёгким поворотом, как
 *     снимки на первом экране фотоветки. Видно верхний.
 *  2. РАЗЛОЖЕНО — нажатие раскладывает: вбок на широком экране, вниз на
 *     телефоне. Анимация одна и та же, меняется только ось.
 *  3. КРУПНО — нажатие на разложенный кадр открывает его во весь экран.
 *
 * ДОСТУПНОСТЬ. Пока стопка сложена, в порядке табуляции ровно одна кнопка —
 * сама стопка: остальные кадры не видны, и водить по ним фокус означало бы
 * гонять читателя по невидимому. Открытый крупный кадр — диалог: фокус
 * уходит на кнопку закрытия, Esc закрывает, фон под ним глохнет.
 */
import { useCallback, useEffect, useRef, useState } from 'react';
import { createPortal } from 'react-dom';

export type Кадр = { src: string; alt: string };

/** Ширина, с которой показываются кадры ноутбука. Та же граница, что у
 *  раскладок страницы (`md:` в Tailwind) — сайт не должен менять правило
 *  ширины в двух местах по-разному. */
const ШИРОКИЙ = '(min-width: 768px)';

export function Shots({
  ноутбук,
  телефон,
  работа,
}: {
  ноутбук: readonly Кадр[];
  телефон: readonly Кадр[];
  /** Имя работы — попадает в подписи кнопок: «показать экраны сайта Toto
   *  Shiro». Без него кнопки трёх работ звучали бы одинаково. */
  работа: string;
}) {
  /* Ширина считается один раз до первого кадра и потом слушается: поворот
     телефона и перетаскивание окна между экранами меняют набор кадров. */
  const [широкий, setШирокий] = useState(() => window.matchMedia(ШИРОКИЙ).matches);
  useEffect(() => {
    const mq = window.matchMedia(ШИРОКИЙ);
    const наСмену = () => setШирокий(mq.matches);
    mq.addEventListener('change', наСмену);
    return () => mq.removeEventListener('change', наСмену);
  }, []);

  const кадры = широкий ? ноутбук : телефон;
  const [разложено, setРазложено] = useState(false);
  const [крупно, setКрупно] = useState<number | null>(null);

  /* Смена ширины складывает стопку обратно: раскладка другая, набор кадров
     другой, и оставлять её разложенной значило бы показать веер из кадров,
     которых читатель не открывал. */
  useEffect(() => {
    setРазложено(false);
    setКрупно(null);
  }, [широкий]);

  return (
    <div
      className={`shots${разложено ? ' is-open' : ''}${широкий ? '' : ' shots--m'}`}
    >
      <ul className="shots-list">
        {кадры.map((к, i) => (
          <li key={к.src} style={{ ['--i' as string]: i }}>
            <button
              type="button"
              className="shots-item"
              /* Пока стопка сложена, доступна только верхняя кнопка: она и
                 раскладывает. Остальные не видны, и фокус по ним ходил бы
                 вслепую. */
              tabIndex={разложено || i === 0 ? 0 : -1}
              aria-label={
                разложено
                  ? `${к.alt}. Открыть крупно`
                  : `Показать экраны сайта ${работа}: ${кадры.length} кадров`
              }
              onClick={() => (разложено ? setКрупно(i) : setРазложено(true))}
            >
              <img
                src={к.src}
                alt={разложено ? к.alt : ''}
                width={широкий ? 1200 : 640}
                height={широкий ? 750 : 1385}
                className="frame block w-full"
                loading="lazy"
                decoding="async"
              />
            </button>
          </li>
        ))}
      </ul>

      {разложено ? (
        <p className="shots-fold">
          <button type="button" className="link-minor" onClick={() => setРазложено(false)}>
            сложить
          </button>
        </p>
      ) : null}

      {крупно !== null ? (
        <Крупно кадр={кадры[крупно]} закрыть={() => setКрупно(null)} />
      ) : null}
    </div>
  );
}

/**
 * Кадр во весь экран. Портал в `body`: иначе увеличенный снимок остался бы
 * внутри колонки работы и обрезался бы её границами.
 */
function Крупно({ кадр, закрыть }: { кадр: Кадр; закрыть: () => void }) {
  const кнопка = useRef<HTMLButtonElement>(null);

  const наКлавишу = useCallback(
    (e: KeyboardEvent) => {
      if (e.key === 'Escape') закрыть();
    },
    [закрыть],
  );

  useEffect(() => {
    /* Фокус уходит на кнопку закрытия: читатель клавиатурой должен попасть в
       открытый кадр, а не остаться позади него. Прокрутка страницы под
       кадром запирается — иначе фон едет вместе с жестом по картинке. */
    кнопка.current?.focus();
    const doc = document.documentElement;
    const было = doc.style.overflow;
    doc.style.overflow = 'hidden';
    window.addEventListener('keydown', наКлавишу);
    return () => {
      doc.style.overflow = было;
      window.removeEventListener('keydown', наКлавишу);
    };
  }, [наКлавишу]);

  return createPortal(
    <div className="shots-zoom" role="dialog" aria-modal="true" aria-label={кадр.alt}>
      {/* Нажатие мимо кадра закрывает — привычный жест. Сам кадр нажатие не
          закрывает: по нему могут водить пальцем, разглядывая. */}
      <button type="button" className="shots-zoom-bg" aria-label="Закрыть" onClick={закрыть} />
      <img src={кадр.src} alt={кадр.alt} className="shots-zoom-img" decoding="async" />
      <button ref={кнопка} type="button" className="shots-zoom-close" onClick={закрыть}>
        закрыть
      </button>
    </div>,
    document.body,
  );
}
