/* ═══ АРХИВ ПЕРЕСОБРАН ВЛАДЕЛИЦЕЙ (Ф42) ═══════════════════════════════════
   «Я плёнку ещё чуть разобрала по папкам». Разобрала не только плёнку —
   второй уровень сменился целиком, и старые правила на нём отдавали `null`,
   то есть молча выбрасывали почти весь архив:

     БЫЛО                        СТАЛО
     цифра/индивидуальная съемка  цифра/девушка/{на улице/…, студия}
     цифра/парная/…               цифра/парная/{…, две девушки}
     цифра/творческая/…           НЕТ ВОВСЕ
     пленка/индивидуальная/…      пленка/девушка/{город,дома,студия,улица}
     пленка/парная/…             пленка/вдвоем/{парная,две девушки,два парня}

   Без правки `normalizeFormat` вернул бы `null` на «девушка» и «вдвоем» —
   это 200 файлов из 254, весь подбор остался бы с четырьмя мужскими кадрами.

   ТЕПЕРЬ ПАПКА НЕСЁТ ДВА РАЗНЫХ ФАКТА, и они разведены по разным полям:
   «девушка»/«парень» — это ПОЛ, а формат у обоих один, «индивидуальная»
   (снимают одного человека). Раньше пол приходилось выковыривать подстрокой
   «мужская» из поля места — теперь он приходит из структуры и живёт в своём
   поле `пол`. Старое чтение подстроки оставлено рядом для файлов, где метка
   ещё лежит в месте.

   «ВДВОЁМ» ШИРЕ, ЧЕМ «ПАРА» (Ф42, дословно: «вдвоём же не подразумевает
   обязательно пару»). Папки `две девушки` и `два парня` — тот же формат
   `парная`, отличаются только составом; ответ «Вдвоём» показывает их
   наравне с романтическими парами. */
function normalizeFormat(raw) {
  if (!raw) return null;
  if (raw.startsWith('индивидуальная')) return 'индивидуальная'; // старое дерево
  if (raw === 'девушка' || raw === 'парень') return 'индивидуальная';
  if (raw === 'парная' || raw === 'вдвоем') return 'парная';
  if (raw === 'творческая') return 'творческая'; // в архиве больше нет, правило оставлено
  return null;
}

/* ═══ АРХИВ ПЕРЕСОБРАН ПОД САМО ДЕРЕВО ВОПРОСОВ (Ф46) ═══════════════════════
   «Я тебе разобрала по папкам все фотографии, чуть-чуть доделай ветку».

   Разобрала не «чуть-чуть»: второй уровень архива теперь — ОТВЕТ НА ПЕРВЫЙ
   ВОПРОС КВИЗА, а дальше папки повторяют ветвление дословно:

     цифра|пленка/
       вайб имеется/
         в одиночку/ девушка/ {город,дома,студия,улица,на улице}
         в одиночку/ парень/
         вдвоем/    {парная, две девушки, два парня, в студии, дома, на улице}
       запечатлеть любовь/
         {в студии, на улице}          ← плёнка
         парная/{галерея, город…, студия, две девушки}   ← цифра

   ЭТО ЛУЧШАЯ РАЗМЕТКА ИЗ ВСЕХ, ЧТО БЫЛИ, и она же решает исходную жалобу.
   Раньше «Запечатлеть любовь» и «Вдвоём» приводили к одному формату
   `парная`, и различить их было нечем — отсюда «появляются варианты из
   вдвоём, хотя это разные тематики». Теперь ветка написана прямо в пути, и
   гадать не нужно: что лежит в `запечатлеть любовь/`, то и есть любовь.

   ВАЖНОЕ СЛЕДСТВИЕ, О КОТОРОМ СТОИТ ЗНАТЬ: `запечатлеть любовь/парная/две
   девушки` (8 кадров) владелица положила ИМЕННО СЮДА, и они остаются в
   ветке любви. Это её сортировка, а не недосмотр разбора: папка «вдвоём» у
   неё отдельная, и если бы кадры были про «просто вдвоём», они лежали бы
   там. Разбор уважает раскладку, а не переспрашивает её.

   Функция возвращает всё четырьмя полями сразу, а не тремя отдельными
   разборщиками пути: части пути связаны между собой (глубина зависит от
   ветки), и три независимых `if`-а по одной строке трижды угадывали бы одно
   и то же. */
function classify(rawFormat, rawPlace) {
  const parts = [rawFormat, ...(rawPlace ? rawPlace.split(' / ') : [])].filter(Boolean);
  const none = { формат: null, пол: null, ветка: null, место: null };
  if (!parts.length) return none;

  const [branch, ...rest] = parts;

  // ── ветка «Запечатлеть любовь» ──────────────────────────────────────
  if (branch === 'запечатлеть любовь') {
    // у цифры внутри ещё уровень `парная/`, у плёнки его нет — снимаем, если есть
    const tail = rest[0] === 'парная' ? rest.slice(1) : rest;
    return { формат: 'парная', пол: null, ветка: 'любовь', место: tail.join(' / ') || null };
  }

  // ── ветка «Вайб имеется» ────────────────────────────────────────────
  if (branch === 'вайб имеется') {
    const [kind, ...tail] = rest;
    if (kind === 'в одиночку') {
      const [gender, ...place] = tail;
      const пол = gender === 'девушка' || gender === 'парень' ? gender : null;
      return {
        формат: 'индивидуальная',
        пол,
        ветка: 'вайб',
        // «парень» без подпапки места — метка пола, не локация: место пустое
        место: place.join(' / ') || null,
      };
    }
    if (kind === 'вдвоем') {
      return { формат: 'парная', пол: null, ветка: 'вайб', место: tail.join(' / ') || null };
    }
    return { формат: null, пол: null, ветка: 'вайб', место: tail.join(' / ') || null };
  }

  /* Старое дерево (до Ф46) — на случай манифеста, собранного раньше. Если
     когда-нибудь исчезнет и оно, подбор просто не найдёт формат и покажет
     честно пустой результат вместо неправильного. */
  if (branch === 'девушка' || branch === 'парень') {
    return { формат: 'индивидуальная', пол: branch, ветка: null, место: rawPlace };
  }
  if (branch === 'парная' || branch === 'вдвоем') {
    return { формат: 'парная', пол: null, ветка: null, место: rawPlace };
  }
  if (branch && branch.startsWith('индивидуальная')) {
    return { формат: 'индивидуальная', пол: null, ветка: null, место: rawPlace };
  }
  return { ...none, место: rawPlace };
}

/** СОСТАВ КАДРА — кто именно вдвоём (Ф46).
 *
 *  Владелица: «при выборе варианта "запечатлеть любовь" появляются варианты
 *  из "вдвоем", хотя это немного разные тематики». Так и было: с Ф42 папки
 *  `две девушки` и `два парня` вошли в формат `парная` — это было верно для
 *  ответа «Вдвоём», но ветка «Запечатлеть любовь» пользуется тем же форматом
 *  и получила их заодно. Формат отвечает на вопрос «сколько людей в кадре»,
 *  а тематика — на «кто они друг другу», и один формат два вопроса не
 *  закрывает.
 *
 *  Поэтому состав — отдельное поле, читается из той же папки третьего
 *  уровня. `парная` здесь значит романтическую пару: так эта папка и
 *  называется у владелицы, и так её понимает ветка «любовь».
 *  `null` у всего, что не «вдвоём», — вопрос к таким кадрам не относится. */
function normalizeComposition(format, rawPlace) {
  if (format !== 'парная') return null;
  if (rawPlace === 'две девушки') return 'две девушки';
  if (rawPlace === 'два парня') return 'два парня';
  return 'парная';
}

/** Пол снимаемого — из СТРУКТУРЫ архива (Ф42), а не из подстроки в месте.
 *  `null` там, где пол не назван: парные съёмки, мини-сет повода, файлы,
 *  лежащие в корне материала без папки формата. */
function normalizeGender(rawFormat, rawPlace) {
  if (rawFormat === 'девушка') return 'девушка';
  if (rawFormat === 'парень') return 'парень';
  if (rawPlace && rawPlace.includes('мужская')) return 'парень'; // наследие старого дерева
  return null;
}

