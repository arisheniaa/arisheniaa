/* ИСПРАВЛЕНО Ф41: «ты отнесла папку "галерея" из папки "исходники" к уличным,
   хотя они больше подходят варианту "в студии" и "дома"».

   Так и было, и это ошибка не разметки владелицы, а вот этой функции.
   Проверка шла по двум подстрокам, «город» и «студия», а всё остальное
   валилось в `природа` последней строкой — как «лес, поле, сад, вода, песок,
   детская площадка». Папка `галерея` (11 кадров) ни одной из подстрок не
   содержала и молча уезжала в природу, то есть в ответ «На улице». Галерея —
   помещение, свет там ставленный и погоды нет: правильный бакет —
   `студия`, тот самый, который обслуживает ответы «В студии» и «Дома»
   (огрубление «дома» → студия описано в `types.ts`).

   Проверка на `галерея` стоит ПЕРЕД `город` намеренно: у части кадров место
   записано как «парная, в студии и в галерее», и они уже попадали в студию
   по подстроке «студия» — порядок это сохраняет, но теперь не зависит от
   того, какое из двух слов встретится в строке первым.

   `природа` осталась последней строкой, но это по-прежнему УГАДЫВАНИЕ по
   остатку. Сейчас в остатке только настоящие открытые места (лес, поле, сад,
   вода, песок, площадка) — проверено по списку всех значений архива. Если
   владелица заведёт новую папку-помещение, она снова уедет в природу, и
   поймать это можно только глазами. Записано как известное ограничение. */
function placeCategory(raw) {
  if (!raw) return null;
  /* СОСТАВ — НЕ МЕСТО (Ф42). В новом дереве третий уровень «вдвоём» несёт не
     локацию, а кто в кадре: `парная`, `две девушки`, `два парня`. Раньше
     любая незнакомая строка падала в `природа` последней строкой — эти
     шестнадцать кадров уехали бы «на улицу», хотя про место в них не
     сказано ничего. Честный ответ — `null`: место неизвестно, бонус за него
     не начисляется, кадр остаётся в пуле формата. */
  if (raw === "парная" || raw === "две девушки" || raw === "два парня") return null;
  if (raw.includes('галере')) return 'студия'; // «галерея», «в галерее» — помещение
  if (raw.includes('студия')) return 'студия'; // включая «парная, в студии и в галерее»
  /* «ДОМА» → СТУДИЯ (Ф42, её прямое разрешение: «если будет не хватать в
     папке "дома" снимков, то можешь брать из "студия"»). Домашних кадров в
     архиве пять, и все плёночные — на ответ «Дома» одного этого мало.
     Огрубление здесь И в `placeMatches` (`pick.ts`) работает в обе стороны:
     домашние кадры видны и по ответу «В студии», студийные — по «Дома». */
  if (raw.includes('дома')) return 'студия';
  if (raw.includes('город')) return 'город'; // включая «мужская, город»
  return 'природа'; // улица, лес, поле, сад, вода, песок, детская площадка
}

function normalizeOccasion(tags) {
  return Array.from(new Set(tags.map((t) => t.split(' / ')[0])));
}

/** Честный alt из подтверждённых тегов, без выдуманных эпитетов (правило,
 *  проверенное на основном сайте: alt обязан описывать факты, не впечатление). */
function buildAlt(entry, format, place) {
  const bits = [];
  if (format) bits.push(`${format} съёмка`);
  else bits.push('кадр из архива');
  if (entry.материал) bits.push(entry.материал);
  if (place) bits.push(place);
  return `Фото: ${bits.join(', ')}.`;
}

