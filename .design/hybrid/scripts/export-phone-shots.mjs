/**
 * ТЕЛЕФОННЫЕ ЭКРАНЫ ПОРТФОЛИО (Ф79).
 *
 * Владелица прислала СВОИ скриншоты с телефона и назвала три опорных кадра:
 * «IMG_4246 — это главная сайта Toto Shiro, IMG_4253 — это моего сайта и
 * IMG_4260 — это Элегии. 5 скриншотов с каждого сайта. найди их».
 *
 * Остальные двенадцать разобраны по контактной странице (все пятнадцать
 * сведены в одну картинку и просмотрены), а не по нумерации: в её порядке
 * есть пропуски, и «пять подряд от опорного» дало бы неверную разбивку —
 * последний кадр её сайта (`4268`) лежит ПОСЛЕ кадров «Элегии».
 *
 * Почему её снимки, а не машинные: браузерный скриншот телефонной ширины —
 * это эмуляция. У настоящего телефона другой шрифтовой рендер, свои поля
 * и статусная строка. В портфолио показывают то, что человек увидит у себя
 * в руках.
 *
 * Исходники лежат ВНЕ репозитория (папка «данные/фотографии/для сайта»):
 * фотоархив в гит не складывается — то же правило, что у `export-photos.mjs`.
 *
 * Запуск из корня репозитория:
 *   node .design/hybrid/scripts/export-phone-shots.mjs
 */
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC = 'C:/Users/Аришения/OneDrive/Рабочий стол/Claude Projects/данные/фотографии/для сайта';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../public/design');
fs.mkdirSync(OUT, { recursive: true });

/* Разбивка по сайтам. Первый в каждом ряду — главная (её опорные кадры),
   дальше по ходу сайта. Исходники 1170×2080, пропорция 0.563. */
const РЯДЫ = {
  toto: ['4246', '4247', '4249', '4251', '4252'],
  arisheniaa: ['4253', '4255', '4256', '4257', '4268'],
  elegia: ['4260', '4261', '4262', '4263', '4264'],
};

/* 620 px по ширине: кадр показывается в стопке шириной около 190 px на
   телефоне, при двойной плотности нужно 380 — запас взят на широкие
   телефоны и на просмотр крупно, где кадр открывается почти во весь экран. */
const Ш = 620;

for (const [сайт, кадры] of Object.entries(РЯДЫ)) {
  for (const [i, номер] of кадры.entries()) {
    const из = path.join(SRC, `IMG_${номер}.PNG`);
    if (!fs.existsSync(из)) {
      console.error(`нет исходника: ${из}`);
      continue;
    }
    const имя = `${сайт}-m${i + 1}.webp`;
    await sharp(из).resize({ width: Ш }).webp({ quality: 80 }).toFile(path.join(OUT, имя));
    console.log(`IMG_${номер} → ${имя}  ${(fs.statSync(path.join(OUT, имя)).size / 1024).toFixed(0)} КБ`);
  }
}
