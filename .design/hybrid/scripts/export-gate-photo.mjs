/**
 * КАДРЫ РАЗВИЛКИ ДЛЯ ТЕЛЕФОНА (Ф67).
 *
 * Владелица: «в мобильной версии поменяем фотографию на эту IMG_0852 и
 * попробуем еще эту IMG_8273 (2)… они находятся на рабочем столе».
 *
 * Оба исходника ВЕРТИКАЛЬНЫЕ (846×1280, 2:3) — и в этом весь смысл замены:
 * прежний кадр развилки горизонтальный (3:2), и на телефоне его приходилось
 * либо резать до середины лица, либо класть полосой поперёк экрана. Съёмка
 * под вертикальный экран решает то, чего не могла решить вёрстка.
 *
 * Ширина 900 px: на телефоне 390 px при двойной плотности нужно 780, запас
 * оставлен на 430-е экраны. Больше смысла нет — кадр стоит фоном.
 *
 * Запуск из корня репозитория:
 *   node .design/hybrid/scripts/export-gate-photo.mjs
 *
 * Исходники лежат ВНЕ репозитория, на рабочем столе владелицы: путь ниже
 * рабочий только на её машине, и это осознанно — фотоархив в гит не
 * складывается (то же правило, что у `export-photos.mjs`).
 */
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC = 'C:/Users/Аришения/OneDrive/Рабочий стол';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../public/gate');
fs.mkdirSync(OUT, { recursive: true });

/* ВЫБРАН ПЕРВЫЙ. Владелица посмотрела оба варианта и выбрала IMG_0852.
   Второй (`gate-b`) оставлен В СПИСКЕ, но его webp удалён из `public/`:
   лежать в сборке неиспользованной сотней килобайт ему незачем, а вернуть
   его — это раскомментировать строку и выполнить скрипт. Пока исходник
   лежит на рабочем столе, восстановление стоит одну команду. */
const КАДРЫ = [
  { файл: 'IMG_0852.JPG', имя: 'gate-a.webp' },
  // { файл: 'IMG_8273 (2).JPG', имя: 'gate-b.webp' }, — не выбран
];

for (const к of КАДРЫ) {
  const из = path.join(SRC, к.файл);
  if (!fs.existsSync(из)) {
    console.error(`нет исходника: ${из}`);
    continue;
  }
  await sharp(из)
    .rotate() // по EXIF: без этого снятый вертикально кадр лёг бы набок
    .resize({ width: 900 })
    .webp({ quality: 82 })
    .toFile(path.join(OUT, к.имя));
  const м = await sharp(path.join(OUT, к.имя)).metadata();
  console.log(`${к.файл} → ${к.имя}  ${м.width}×${м.height}  ${(fs.statSync(path.join(OUT, к.имя)).size / 1024).toFixed(0)} КБ`);
}
