await section('6. стрелка-подсказка', async () => {
  const ctx = await browser.newContext({ viewport: { width: 1400, height: 900 } });
  const page = await ctx.newPage();
  const errs = [];
  page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  page.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
  await page.goto(MAIN, { waitUntil: 'networkidle' });

  let hintCount = await page.locator('.nav-hint').count();
  note(RED ? hintCount > 0 : hintCount === 0, `на нулевом скролле стрелка НЕ смонтирована (П7): найдено ${hintCount}`);

  /* Прокрутка ЗА ПЕРВЫЙ ЭКРАН по его собственному краю, а не на долю от
     высоты документа. Прежние «35 % высоты» читали `scrollHeight` в момент,
     когда раскладка могла быть ещё не досчитана: на недосчитанной высоте
     35 % приходились внутрь первого экрана, подсказка по своему условию не
     появлялась вовсе, и проверка ждала её тридцать секунд и падала. Условие
     показа — «первый экран ушёл из кадра» (`NavHint.tsx`), поэтому и целимся
     ровно в него: нижний край `#hero` плюс запас. */
  await page.evaluate(() => {
      const hero = document.getElementById('hero');
      const y = hero ? hero.getBoundingClientRect().bottom + window.scrollY + 40 : window.innerHeight * 1.4;
      window.scrollTo({ top: y, left: 0, behavior: 'instant' });
    });
  await page.waitForTimeout(700);
  hintCount = await page.locator('.nav-hint').count();
  note(RED ? hintCount === 0 : hintCount === 1, `после прокрутки вниз стрелка появляется (найдено ${hintCount})`);
  if (hintCount === 1) {
    const shown = await page.locator('.nav-hint').getAttribute('data-show');
    note(RED ? shown !== '' : shown === '', '`data-show` реально проставлен спустя время после появления (не просто «элемент есть в DOM»)');
    const href = await page.locator('.nav-hint').getAttribute('href');
    note(href === '/storyboard.html', `стрелка ведёт на страницу фичи (получено: ${href})`);
  }

  // форсируем мгновенный скролл (обходя `scroll-behavior: smooth` — иначе
  // тест зависит от длительности анимации плавного скролла, а не от логики)
  await page.evaluate(() => {
    document.documentElement.style.scrollBehavior = 'auto';
    document.getElementById('kontakt').scrollIntoView();
  });
  await page.waitForTimeout(400);
  hintCount = await page.locator('.nav-hint').count();
  /* ПРОВЕРКА ПЕРЕВЁРНУТА Ф55, А НЕ УДАЛЕНА. Было: «у секции контактов
     стрелка гаснет» — это следовало из формулировки Ф33 «перед контактами».
     Владелица отменила ровно её: «сделай так, чтобы стрелка-указатель
     "загляните сюда" горела до конца, даже когда находишься на последнем
     разделе, чтобы он продолжал привлекать внимание». Теперь проверяется
     противоположное — и это не ослабление: у секции контактов стрелка
     обязана БЫТЬ, а раз так, утверждение осталось таким же строгим, просто
     с другим ожиданием. Условие «пока виден первый экран — стрелки нет»
     (проверка выше) не тронуто: оно из другого правила (П7), а не из
     отменённой формулировки. */
  note(RED ? hintCount === 0 : hintCount === 1, `у секции контактов стрелка ПРОДОЛЖАЕТ гореть (найдено ${hintCount})`);

  const navCount = await page.locator('nav').count();
  note(navCount === 2, `стрелка не создала третий лендмарк <nav> (найдено ${navCount}, ожидались те же 2, что и раньше)`);
  note(errs.length === 0, `консоль чиста на главной с учётом стрелки${errs.length ? ': ' + errs.slice(0, 3).join(' | ') : ''}`);

  await ctx.close();
});

